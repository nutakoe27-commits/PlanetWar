// pw_core — job system с воровством работы.
//
// Тик симуляции распараллеливается по системам галактики: на 4 ядрах это
// прямой выигрыш, а горячие системы всё равно считаются независимо.
//
// ДИСЦИПЛИНА ДЕТЕРМИНИЗМА. Многопоточность не имеет права влиять на результат.
// Отсюда два железных правила для тела parallelFor:
//   1. Оно читает общие данные и пишет ТОЛЬКО в свой диапазон индексов.
//   2. Всё, что накапливается между чанками (события, спавны, транзакции),
//      складывается в буфер своего чанка и применяется ПОСЛЕ барьера строго
//      в порядке возрастания индекса.
// Нарушение любого из них даёт расхождение симуляции, которое воспроизводится
// раз в сотню запусков и ищется неделями.
#pragma once

#include <cstdint>
#include <functional>
#include <memory>

namespace pw {

class JobSystem {
public:
    /// workers == 0 -> по числу ядер минус один (главный поток тоже работает).
    /// workers < 0  -> полностью синхронный режим: удобно для тестов и для
    ///                 воспроизведения багов, когда потоки только мешают.
    explicit JobSystem(int workers = 0);
    ~JobSystem();

    JobSystem(const JobSystem&) = delete;
    JobSystem& operator=(const JobSystem&) = delete;

    int workerCount() const;

    /// Поставить задачу в очередь. Завершения ждать через waitIdle().
    void dispatch(std::function<void()> job);

    /// Разбить [0, count) на куски по grain и обработать параллельно.
    /// Вызывающий поток тоже участвует в работе, а не простаивает.
    /// Возвращает управление, когда обработан ВЕСЬ диапазон.
    void parallelFor(int64_t count, int64_t grain,
                     const std::function<void(int64_t begin, int64_t end)>& body);

    /// Дождаться, пока очередь опустеет. Вызывающий поток помогает разгребать.
    void waitIdle();

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

}  // namespace pw
