// pw_core — запись PNG без внешних зависимостей.
//
// Живёт в ядре, а не в графическом слое, потому что нужна обоим и не зависит
// ни от чего: кадру рендера, чтобы его можно было сравнить с эталоном, и
// симуляции, чтобы посмотреть на процедурную галактику глазами.
//
// Второе не менее важно первого. Процедурная генерация — та область, где
// все тесты зелёные, а картинка при этом никуда не годится: первая версия
// генератора кораблей делала флот, летящий кормой вперёд, и ни один автотест
// этого не поймал.
//
// Библиотеку сжатия ради этого не тянем. PNG допускает поток deflate из
// «сохранённых» блоков, то есть вообще без сжатия. Файл крупнее, но это
// отладочный артефакт, а не игровой ресурс: игровые текстуры печёт Blender.
#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace pw {

struct Rgba8 {
    uint8_t r = 0, g = 0, b = 0, a = 255;
};

/// Прочитать PNG в RGBA8.
///
/// Своя реализация, без сторонних библиотек — по той же причине, по которой
/// свой движок: проект должен собираться и поддерживаться одним человеком,
/// а каждая внешняя зависимость это обещание ломает. Заодно снимается
/// целый класс уязвимостей: разбор картинок — исторически самое дырявое
/// место в играх, и своя строгая реализация без экзотических режимов
/// безопаснее универсальной.
///
/// Поддерживается ровно то, что производит наш ассетный пайплайн и что
/// пишет Blender: 8 бит на канал, цветовые типы 0/2/4/6, без чересстрочной
/// развёртки. Всё остальное честно отвергается, а не читается наполовину.
///
/// false — файл не открылся, повреждён или в неподдерживаемом варианте.
bool readPng(const std::string& path, std::vector<Rgba8>& pixels, int& width, int& height);

/// То же, но из памяти: на Android ассеты лежат внутри apk и файла нет.
bool decodePng(const uint8_t* data, size_t size, std::vector<Rgba8>& pixels, int& width,
               int& height);

bool writePng(const std::string& path, const std::vector<Rgba8>& pixels,
              int width, int height);

}  // namespace pw
