// Где лежат собранные ассеты — общий поиск для всех тестов рендера.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Каждый тест искал ассеты сам, перебирая
// «assets/build/…», «../assets/build/…» и «../../assets/build/…». Из корня
// репозитория это работало, а из каталога сборки — нет: ctest запускает
// бинарь в build/<профиль>/engine/render/tests, а это ЧЕТЫРЕ уровня
// до корня, и трёх «..» не хватало.
//
// Тесты при этом были ЗЕЛЁНЫМИ. Они честно печатали «ассеты не собраны —
// пропускаю» и завершались успехом, поэтому ни ctest, ни verify.sh, ни CI
// не замечали, что проверки манифеста планет, шрифта, атласа кораблей
// и атласа интерфейса не выполнялись вовсе. Обнаружилось случайно: тот же
// тест, запущенный руками из корня, падал.
//
// Отсюда правило: путь к ассетам НЕ УГАДЫВАЕТСЯ фиксированным числом
// «..», а ищется подъёмом вверх до тех пор, пока файл не найдётся.

#include <fstream>
#include <string>

namespace pw::render::testing {

/// Найти файл ассетов, поднимаясь вверх от текущего каталога.
///
/// `relative` задаётся от корня репозитория, например
/// "assets/build/planets.json". Пустая строка — файла нет нигде,
/// то есть ассеты действительно не собраны.
inline std::string findAsset(const std::string& relative) {
    std::string prefix;
    // Восемь уровней с запасом: глубже каталога сборки тестов не бывает
    // ни на одном профиле, а бесконечный цикл при отсутствии файла нам
    // не нужен.
    for (int depth = 0; depth < 8; ++depth) {
        const std::string candidate = prefix + relative;
        std::ifstream probe(candidate);
        if (probe) return candidate;
        prefix += "../";
    }
    return {};
}

}  // namespace pw::render::testing
