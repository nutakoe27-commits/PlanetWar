#pragma once

// Эффекты на карте: то, чем мир отвечает на события.
//
// ЗАЧЕМ ОНИ НУЖНЫ.
//
// Всё важное в этой игре происходит там, куда игрок в этот момент
// не смотрит. Колония основана в соседнем рукаве, планету осадили на другом
// конце карты, бой случился, пока открыт список флотов. Мир при этом
// меняется МГНОВЕННО: точка на карте была ничьей, стала своей, и различить
// «только что взяли» от «было всегда» нельзя ничем, кроме памяти.
//
// Уведомление в углу об этом говорит словами. Но слова читают, а вспышку
// видят: глаз человека устроен так, что замечает ДВИЖЕНИЕ на периферии
// раньше, чем что-либо ещё. Кольцо, разошедшееся по карте там, где
// случилось событие, отвечает на вопрос «где» до того, как игрок дочитает
// «что».
//
// ЭФФЕКТ НИЧЕГО НЕ ЗНАЧИТ И НИЧЕГО НЕ РЕШАЕТ. Он не влияет ни на мир,
// ни на попадание щелчка, ни на порядок отрисовки чего-либо ещё. Пропав,
// он не оставляет следа. Поэтому он и живёт целиком в клиенте, а сервер
// о нём не знает: детерминизм симуляции ему безразличен.
//
// РИСУЮТСЯ ОТРЕЗКАМИ, А НЕ СПРАЙТАМИ.
//
// Кольцо и трасса — это геометрия, а не картинка: у них нет ни модели,
// ни текстуры, и печь их в Blender было бы нечего. Карта и без того
// рисует гиперлинии отрезками, так что новых способов рисовать не
// появляется. Заодно эффект любого размера остаётся одинаково чётким:
// растянутый спрайт кольца на общем плане превратился бы в мыло.

#include <cstdint>
#include <vector>

#include "pw/render/map_view.h"
#include "pw/rhi/rhi.h"

namespace pw::render {

/// Что случилось. Вид эффекта выбирается по СМЫСЛУ события, а не по цвету:
/// одинаковые кольца разных цветов игрок различает хуже, чем разные формы.
enum class EffectKind : uint8_t {
    /// Высадка колонии: кольцо расходится наружу — империя выросла.
    Colonized = 0,
    /// Планета сменила хозяина силой: кольцо СХОДИТСЯ внутрь. Направление
    /// противоположно колонизации намеренно — «пришли извне и сдавили».
    Captured,
    /// Свою планету забрали. То же схождение, но красным и вдвое дольше:
    /// это худшая новость в игре, и она обязана держаться на экране.
    Lost,
    /// Началась осада: пульсирующее кольцо, пока идёт.
    Sieged,
    /// Сражение: короткие лучи от центра во все стороны.
    Battle,
    /// Здание достроено: кольцо и крест — тихое, спокойное событие.
    Built,
    /// Приказ принят: кольцо в точке, куда отдан приказ. Отклик на щелчок,
    /// а не новость о мире.
    Order,
    Count
};

/// Один живой эффект.
struct Effect {
    EffectKind kind = EffectKind::Colonized;
    float x = 0.0f, y = 0.0f;   // мировые координаты
    float radius = 1.0f;        // характерный размер, в мировых единицах
    float age = 0.0f;           // сколько секунд живёт
    float life = 1.0f;          // сколько проживёт всего
    EmpireColor color{1.0f, 1.0f, 1.0f};
    uint32_t seed = 0;          // разброс лучей у сражения

    float phase() const { return life > 0.0f ? age / life : 1.0f; }
    bool dead() const { return age >= life; }
};

/// Сколько эффектов живёт одновременно.
///
/// Предел нужен не ради памяти, а ради ЧИТАЕМОСТИ. Волна кризиса приносит
/// десяток сражений разом, и без предела карта на секунду превращается
/// в мигающую ёлку, на которой не видно ни одного из событий. Старшие
/// вытесняются первыми: свежее событие важнее позавчерашнего.
inline constexpr size_t kMaxEffects = 64;

class Effects {
public:
    /// Завести эффект. `radius` — в мировых единицах; для системы это
    /// примерно её видимый размер на карте.
    void spawn(EffectKind kind, float worldX, float worldY, float radius,
               const EmpireColor& color, uint32_t seed = 0);

    /// Состарить на шаг кадра и убрать отжившие.
    void update(float deltaSeconds);

    void clear() { live_.clear(); }
    size_t count() const { return live_.size(); }
    const std::vector<Effect>& live() const { return live_; }

    /// Досыпать геометрию в кадр карты.
    ///
    /// Именно ДОСЫПАТЬ, а не рисовать своим вызовом: эффекты обязаны
    /// лечь тем же камерным преобразованием, что и карта, и попасть
    /// в ту же пачку отрезков. Отдельный вызов отрисовки означал бы
    /// вторую камеру и второй способ ошибиться.
    void build(MapFrame& out) const;

private:
    std::vector<Effect> live_;
};

/// Сколько живёт эффект этого вида, в секундах. Отдельной функцией,
/// чтобы сроки лежали в одном месте и их можно было сравнить глазами.
float effectLifetime(EffectKind kind);

}  // namespace pw::render
