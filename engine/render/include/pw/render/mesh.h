#pragma once

// Сетки: загрузка моделей, испечённых Blender.
//
// Формат свой (.pwm), и это осознанно. Движку нужны ровно положение,
// нормаль и развёртка; разбирать ради трёх атрибутов glTF значит тащить
// в pw_render либо разбор JSON с base64, либо стороннюю библиотеку —
// а движок обязан оставаться таким, чтобы его мог держать один человек.
//
// Файлы коммитятся в репозиторий, как и SPIR-V, и по той же причине:
// сборка не должна зависеть от того, стоит ли у кого-то Blender.
//
//   'P','W','M','1'   магия
//   uint32            число вершин
//   uint32            число индексов
//   вершины           по 8 float: x y z nx ny nz u v
//   индексы           по uint32, треугольниками

#include <cstdint>
#include <string>
#include <vector>

#include "pw/rhi/rhi.h"

namespace pw::render {

/// Сетка в памяти: то, что прочитано из файла и ещё не уехало на устройство.
struct MeshData {
    std::vector<rhi::MeshVertex> vertices;
    std::vector<uint32_t> indices;

    bool empty() const { return vertices.empty() || indices.empty(); }
    /// Габарит по любой оси: половина стороны куба, накрывающего сетку.
    float extent() const;
};

/// Прочитать .pwm. false — файла нет, он битый или не наш.
///
/// Проверяется всё: и магия, и то, что индексы не выходят за число вершин.
/// Файл лежит рядом с игрой и может быть повреждён чем угодно, а видеокарта
/// на индекс за границей отвечает не исключением, а зависанием драйвера.
bool loadMesh(const std::string& path, MeshData& out, std::string* error = nullptr);

/// Сетка, построенная кодом.
///
/// Единственное исключение из правила «вся геометрия из Blender», и оно
/// узкое: это ОРБИТА — не модель, а разметка, у которой нет ни материала,
/// ни поверхности, ни автора. Печь её в Blender значило бы завести файл
/// ради двух чисел, радиуса и толщины.
MeshData makeOrbitRing(uint32_t segments = 128, float thickness = 0.004f);

}  // namespace pw::render
