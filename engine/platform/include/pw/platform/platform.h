// pw_platform — инициализация платформы, время, сведения о системе.
//
// Весь SDL спрятан внутри этого модуля. Ни один его заголовок не появляется
// в публичном интерфейсе, поэтому зависимость заменима, не задевая ни движок,
// ни игру. Проверка тривиальна: grep -r SDL engine/platform/include не должен
// находить ничего.
//
// ВРЕМЯ ЗДЕСЬ — НЕ ВРЕМЯ СИМУЛЯЦИИ. Реальные часы недетерминированы, поэтому
// в pw_sim их быть не может. Здесь они нужны для кадров, профилирования
// и сетевых таймаутов — того, что на состояние мира не влияет.
#pragma once

#include <cstdint>

namespace pw {

/// Поднять платформу. Обязательно до создания окна.
///
/// headless — не поднимать видеоподсистему вообще. Это режим сервера, тестов
/// рендера и CI: там нет ни дисплея, ни видеокарты, и попытка открыть видео
/// закончилась бы ошибкой на пустом месте.
bool initPlatform(bool headless = false);

/// Поднята ли видеоподсистема. pw_rhi по этому флагу решает, нужны ли ему
/// расширения поверхности, или он рисует в память.
bool platformHasVideo();
void shutdownPlatform();

/// Монотонные часы в наносекундах. Не привязаны к настенному времени
/// и не прыгают при переводе часов.
uint64_t nowNanos();
double nowSeconds();

int cpuCount();

/// Последняя ошибка платформы. Пустая строка, если ошибок не было.
const char* platformError();

}  // namespace pw
