// pw_rhi — абстракция графического API.
//
// Один бэкенд на все платформы: Vulkan. На маках и айфонах он идёт поверх
// Metal через MoltenVK — см. ADR-013. Второй, нативный бэкенд на Metal нам
// сейчас не нужен: 2.5D-карта рисуется единицами вызовов отрисовки, и
// накладные расходы трансляции там неразличимы, а стоимость второй
// реализации — месяцы.
//
// ДВА РЕЖИМА ЦЕЛИ, и второй не менее важен первого:
//   оконный    — поверхность из окна, изображение показывается на экране;
//   безголовый — рисуем в память, без окна и без видеокарты.
//
// Безголовый режим существует не для галочки. Он позволяет проверять рендер
// автоматически: отрисовать кадр в CI, считать пиксели и сравнить с эталоном.
// Иначе графика проверяется только глазами и только тогда, когда кто-то
// удосужился посмотреть.
#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include "pw/core/png.h"

namespace pw {
class Window;
}

namespace pw::rhi {

// Тип пикселя и запись PNG живут в ядре: они не зависят от графического
// API и нужны в том числе симуляции — посмотреть на процедурную галактику.
using pw::Rgba8;
using pw::writePng;

struct DeviceDesc {
    /// Слои проверки Vulkan. Ловят неверное использование API там, где оно
    /// иначе проявилось бы порчей памяти или чёрным экраном.
    bool validation = false;

    /// nullptr — безголовый режим.
    const Window* window = nullptr;

    int width = 1280;   // размер цели в безголовом режиме
    int height = 720;
};

struct ClearColor {
    float r = 0.0f, g = 0.0f, b = 0.0f, a = 1.0f;
};

/// Один спрайт. Всё, что отличает его от соседа, — здесь.
///
/// Раскладка совпадает с поэкземплярными атрибутами sprite.vert байт в байт:
/// массив этих структур уходит в видеопамять как есть, без перекладки.
struct SpriteInstance {
    float x = 0.0f, y = 0.0f;                   // центр в мировых координатах
    float halfWidth = 1.0f, halfHeight = 1.0f;
    float u0 = 0.0f, v0 = 0.0f, u1 = 1.0f, v1 = 1.0f;   // прямоугольник в атласе
    /// Тон УМНОЖАЕТСЯ на текстуру: спрайты испечены серыми, цвет империи
    /// берётся отсюда. Один атлас на всех игроков вместо копии под каждый цвет.
    float r = 1.0f, g = 1.0f, b = 1.0f, a = 1.0f;
    /// Поворот в ОБОРОТАХ, как и везде в проекте, а не в радианах.
    float rotationTurns = 0.0f;
};

struct LineVertex {
    float x = 0.0f, y = 0.0f;
    float r = 1.0f, g = 1.0f, b = 1.0f, a = 1.0f;
};

/// Куда смотрит камера и с каким увеличением.
struct Camera {
    float centerX = 0.0f, centerY = 0.0f;
    /// Сколько мировых единиц влезает по высоте экрана. Задаём высоту,
    /// а не ширину: иначе на широком мониторе игрок видел бы больше карты,
    /// чем на обычном, — то есть преимущество за форму монитора.
    float worldHeight = 1000.0f;

    /// Куда смотрит ось Y.
    ///
    /// У карты вверх — как на любой карте. У экранных панелей вниз —
    /// как принято в интерфейсах, где начало в левом верхнем углу
    /// и единица равна пикселю.
    ///
    /// Это не мелочь оформления: от направления зависит, какой край
    /// текстуры окажется вверху экрана. Шейдер берёт ответ отсюда,
    /// иначе в одном из двух режимов картинка выходит зеркальной.
    bool yDown = false;
};

/// Дескриптор текстуры. Непрозрачный: тип Vulkan наружу не выпускается.
using TextureHandle = uint32_t;
inline constexpr TextureHandle kInvalidTexture = 0;

// ---------------------------------------------------------------------------
// Трёхмерная часть
//
// Карта галактики остаётся плоской: она карта, и объём ей не нужен. А вот
// ВИД СИСТЕМЫ — это место, куда игрок приходит смотреть на свои планеты,
// и там плоские кружки ощущаются схемой, а не миром. Поэтому рядом со
// спрайтовым конвейером живёт второй, сеточный, с буфером глубины
// и настоящим освещением.
// ---------------------------------------------------------------------------

/// Вершина сетки. Раскладка совпадает с атрибутами mesh.vert байт в байт.
struct MeshVertex {
    float x = 0.0f, y = 0.0f, z = 0.0f;
    float nx = 0.0f, ny = 0.0f, nz = 1.0f;
    float u = 0.0f, v = 0.0f;
};

/// Дескриптор сетки: вершины плюс индексы, уже в памяти устройства.
using MeshHandle = uint32_t;
inline constexpr MeshHandle kInvalidMesh = 0;

/// Один экземпляр сетки.
///
/// Матрица модели хранится тремя осями и переносом, а не полной 4x4:
/// нижняя строка у аффинного преобразования всегда (0,0,0,1), и возить
/// её через шину для каждой из тысяч построек — это чистые потери.
struct MeshInstance {
    float axisX[3] = {1.0f, 0.0f, 0.0f};
    float axisY[3] = {0.0f, 1.0f, 0.0f};
    float axisZ[3] = {0.0f, 0.0f, 1.0f};
    float origin[3] = {0.0f, 0.0f, 0.0f};

    /// Тон УМНОЖАЕТСЯ на текстуру. Планеты испечены нейтральными, а цвет
    /// класса и подсветка владельца приходят отсюда: один набор текстур
    /// на всю галактику вместо копии под каждый оттенок.
    float r = 1.0f, g = 1.0f, b = 1.0f, a = 1.0f;

    /// Самосвечение: 0 — обычное тело, 1 — звезда, которая светит сама
    /// и не нуждается во внешнем источнике.
    float emissive = 0.0f;
    /// Сила контурной подсветки. Ею рисуется атмосфера и ею же выделяется
    /// выбранная планета — глазу это читается как «объект в фокусе».
    float rim = 0.0f;
    /// Насколько поверхность зеркальна. Океан бликует, камень нет.
    float gloss = 0.2f;
    /// Мягкий ореол. Больше нуля — прозрачность падает к КРАЮ силуэта:
    /// оболочка гаснет по мере того, как поверхность уходит от взгляда.
    ///
    /// Ровно это и нужно свечению вокруг звезды. Плоская оболочка
    /// с постоянной прозрачностью даёт резкое кольцо — глаз читает его
    /// как ошибку, а не как свет: настоящее свечение спадает плавно.
    float halo = 0.0f;
};

/// Камера в пространстве и единственный источник света сцены.
///
/// Свет один и лежит в камере намеренно: в звёздной системе светит
/// звезда, и второго источника там взяться неоткуда. Схема освещения,
/// выведенная из предмета, а не из общности, экономит и шейдер, и мысли.
struct Camera3D {
    float eyeX = 0.0f, eyeY = -60.0f, eyeZ = 35.0f;
    float targetX = 0.0f, targetY = 0.0f, targetZ = 0.0f;
    /// Куда «вверх». Мир Z-вверх, как в Blender: модели приезжают оттуда,
    /// и переворачивать их на входе значило бы вводить ошибку на ровном месте.
    float upX = 0.0f, upY = 0.0f, upZ = 1.0f;

    /// Угол обзора по вертикали в ОБОРОТАХ, как и все углы в проекте.
    /// 0.1 оборота — это 36 градусов: спокойная перспектива без рыбьего глаза.
    float fovTurns = 0.1f;
    float nearPlane = 0.5f;
    float farPlane = 4000.0f;

    /// Светило: положение и цвет.
    float lightX = 0.0f, lightY = 0.0f, lightZ = 0.0f;
    float lightR = 1.0f, lightG = 0.96f, lightB = 0.9f;
    /// Заполняющий свет. Без него ночная сторона планеты — чёрная дыра
    /// в кадре, а не тёмная сторона: глаз читает это как дырку в геометрии.
    float ambient = 0.06f;
};

/// Матрица «вид умножить на проекцию», по столбцам.
///
/// Открыта наружу намеренно: выбор мышью обязан проецировать точки ТОЙ ЖЕ
/// матрицей, какой рисует конвейер. Две похожие копии математики разойдутся
/// — и курсор начнёт промахиваться мимо того, что видит глаз, причём
/// заметно это станет только на нестандартном соотношении сторон.
void viewProjectionMatrix(const Camera3D& camera, float aspect, float out[16]);

/// Спроецировать точку мира в доли экрана.
///
/// Возвращает false, если точка за камерой. `outX`/`outY` — доли от 0 до 1,
/// начало в левом верхнем углу; `outDepth` — расстояние вдоль взгляда.
bool projectPoint(const Camera3D& camera, float aspect, float x, float y, float z,
                  float& outX, float& outY, float& outDepth);

/// Устройство, цель отрисовки и конвейеры.
///
/// Конвейеров два: спрайты и линии. Разделение не косметическое —
/// линия связывает две произвольные точки, и растягивать под неё
/// повёрнутый квадрат значило бы считать угол и длину на процессоре
/// для каждого из тысяч рёбер графа.
class Device {
public:
    Device();
    ~Device();

    Device(const Device&) = delete;
    Device& operator=(const Device&) = delete;

    bool init(const DeviceDesc& desc);
    void shutdown();

    bool valid() const;
    const std::string& adapterName() const;
    bool headless() const;

    /// Сколько ошибок насчитали проверочные слои за всё время работы.
    ///
    /// Ноль — единственное допустимое значение. Ошибка проверочных слоёв
    /// означает, что программа нарушает спецификацию Vulkan: где-то она
    /// сработает, где-то упадёт, и «у меня работает» ничего не значит.
    /// Прогон обязан на этом падать, поэтому число доступно снаружи.
    static uint64_t validationErrors();

    int targetWidth() const;
    int targetHeight() const;

    /// Собрать графический конвейер из скомпилированного SPIR-V.
    /// Шейдеры компилируются на сборке и коммитятся — как и таблицы
    /// тригонометрии, по той же причине: результат обязан быть одинаковым
    /// у всех, а не зависеть от версии компилятора шейдеров на машине.
    bool createPipeline(const std::vector<uint8_t>& vertexSpirv,
                        const std::vector<uint8_t>& fragmentSpirv);

    bool beginFrame(const ClearColor& clear);
    /// Отрисовать вершины текущим конвейером. Вершины задаёт сам шейдер —
    /// буфера вершин на этом этапе ещё нет.
    void draw(uint32_t vertexCount);
    bool endFrame();

    /// Собрать конвейер спрайтов: инстансированный квадрат с атласом.
    bool createSpritePipeline(const std::vector<uint8_t>& vertexSpirv,
                              const std::vector<uint8_t>& fragmentSpirv);
    /// Собрать конвейер линий.
    bool createLinePipeline(const std::vector<uint8_t>& vertexSpirv,
                            const std::vector<uint8_t>& fragmentSpirv);

    /// Загрузить текстуру RGBA8. Данные копируются, вызывающий их не держит.
    TextureHandle createTexture(int width, int height, const Rgba8* pixels);

    /// Задать камеру на кадр. Соотношение сторон берётся из цели.
    void setCamera(const Camera& camera);

    /// Отрисовать спрайты одним вызовом.
    ///
    /// Данные копируются в кадровый буфер: он переиспользуется, поэтому
    /// вызывающий может собирать спрайты в обычный вектор и не думать
    /// о времени жизни.
    void drawSprites(const SpriteInstance* instances, size_t count, TextureHandle atlas);

    /// Отрисовать отрезки. Вершины идут парами.
    void drawLines(const LineVertex* vertices, size_t count);

    // --- трёхмерная часть ---

    /// Собрать сеточный конвейер: глубина, отсечение задних граней, свет.
    bool createMeshPipeline(const std::vector<uint8_t>& vertexSpirv,
                            const std::vector<uint8_t>& fragmentSpirv);

    /// Собрать конвейер СВЕЧЕНИЯ: та же геометрия, но глубина только
    /// проверяется и не пишется, а цвет складывается, а не замещает.
    ///
    /// Без отдельного состояния прозрачные оболочки — корона звезды,
    /// атмосфера — записывали бы себя в буфер глубины и закрывали всё,
    /// что за ними: звезду загораживала бы её собственная корона.
    bool createGlowPipeline(const std::vector<uint8_t>& vertexSpirv,
                            const std::vector<uint8_t>& fragmentSpirv);

    /// Загрузить сетку. Данные копируются в память устройства и живут
    /// до shutdown: модели планет грузятся один раз за запуск.
    MeshHandle createMesh(const MeshVertex* vertices, size_t vertexCount,
                          const uint32_t* indices, size_t indexCount);

    /// Задать камеру и свет на кадр.
    void setCamera3D(const Camera3D& camera);

    /// Отрисовать экземпляры одной сетки одним вызовом.
    void drawMeshes(MeshHandle mesh, const MeshInstance* instances, size_t count,
                    TextureHandle texture);

    /// То же, но конвейером свечения: складывается с уже нарисованным
    /// и не пишет глубину.
    void drawGlow(MeshHandle mesh, const MeshInstance* instances, size_t count,
                  TextureHandle texture);

    /// Считать цель в память. Только безголовый режим.
    /// Ради этого метода безголовый путь и написан: он превращает проверку
    /// картинки из ручного разглядывания в обычный автотест.
    bool readback(std::vector<Rgba8>& out) const;

    const std::string& lastError() const;

private:
    struct Impl;
    Impl* impl_ = nullptr;
};

}  // namespace pw::rhi
