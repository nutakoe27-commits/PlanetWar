#pragma once

// Надёжный упорядоченный канал поверх ненадёжного транспорта.
//
// Зачем он нужен именно такой. В игре есть два разных вида данных, и путать
// их дорого:
//
//   — КОМАНДЫ («веди флот в систему 42», «построй крейсер») обязаны дойти
//     ровно один раз и в том порядке, в котором игрок их отдал. Потерять
//     команду — значит потерять ход игрока; применить дважды — построить
//     два корабля вместо одного; переставить — отправить флот не туда;
//   — СОСТОЯНИЕ (где сейчас флоты, сколько ресурсов) не нуждается ни в
//     надёжности, ни в порядке: свежий снапшот полностью заменяет прошлый,
//     и переслать устаревший — только зря потратить канал.
//
// Здесь реализовано первое. Второе идёт мимо этого канала — просто в теле
// пакета, и потеря такого пакета не стоит ничего.
//
// Устройство: у каждого сообщения свой номер. Сообщение едет в пакетах,
// пока пакет с ним не подтвердят. Получатель отбрасывает дубли по номеру
// и выдаёт сообщения строго по возрастанию номера, придерживая пришедшие
// раньше срока.

#include <cstdint>
#include <vector>

#include "pw/net/bitstream.h"
#include "pw/net/sequence.h"

namespace pw::net {

/// Предел на одно сообщение. Больше — это уже снапшот, ему сюда не надо.
inline constexpr uint32_t kMaxMessageSize = 1024;
/// Сколько неподтверждённых сообщений канал согласен держать.
///
/// Очередь конечна намеренно: если собеседник перестал подтверждать, канал
/// обязан сказать об этом отправителю, а не расти, пока не кончится память.
inline constexpr uint32_t kMaxQueuedMessages = 256;
/// Насколько далеко вперёд получатель готов придержать пришедшее не по порядку.
inline constexpr uint32_t kReorderWindow = 256;

class ReliableChannel {
public:
    // --- отправка ---

    /// Поставить сообщение в очередь.
    ///
    /// false означает, что очередь переполнена: собеседник давно ничего не
    /// подтверждает. Врать «отправлено» в такой ситуации нельзя — игрок
    /// должен увидеть, что связь потеряна.
    bool send(const void* data, size_t size);

    /// Уложить в пакет столько сообщений, сколько поместится.
    ///
    /// `packetSequence` запоминается, чтобы подтверждение этого пакета
    /// закрыло именно эти сообщения.
    uint32_t pack(ByteWriter& writer, uint16_t packetSequence);

    /// Пакет дошёл: сообщения из него больше не пересылаем.
    void onPacketAcked(uint16_t packetSequence);
    /// Пакет потерян: сообщения из него уедут со следующим.
    void onPacketLost(uint16_t packetSequence);

    // --- приём ---

    /// Разобрать сообщения из пакета. false — пакет битый.
    bool unpack(ByteReader& reader);

    /// Забрать следующее готовое сообщение. Порядок строго тот же, в котором
    /// отправитель их отдал.
    bool receive(std::vector<uint8_t>& out);

    // --- состояние ---

    /// Сколько сообщений ждёт подтверждения.
    uint32_t queued() const;
    /// Сколько пришло не по порядку и ждёт предшественников.
    uint32_t held() const;
    bool empty() const { return queued() == 0; }

private:
    struct Outgoing {
        uint16_t id = 0;
        bool used = false;
        bool inFlight = false;   // уже уехало в неподтверждённом пакете
        std::vector<uint8_t> payload;
    };

    struct PacketRecord {
        uint16_t sequence = 0;
        bool used = false;
        std::vector<uint16_t> ids;
    };

    struct Incoming {
        uint16_t id = 0;
        bool used = false;
        std::vector<uint8_t> payload;
    };

    static constexpr uint32_t kPacketSlots = kAckWindow * 4;

    Outgoing outgoing_[kMaxQueuedMessages];
    PacketRecord packets_[kPacketSlots];
    Incoming incoming_[kReorderWindow];

    // Обе стороны начинают нумерацию с нуля. Это не мелочь: первая версия
    // брала за точку отсчёта номер ПЕРВОГО пришедшего сообщения — и теряла
    // порядок ровно тогда, когда терялся первый пакет, то есть в самом
    // частом случае. Заодно это закрывает возможность собеседнику одним
    // сообщением с большим номером протолкнуть получателя вперёд.
    uint16_t nextOutgoingId_ = 0;
    uint16_t nextExpectedId_ = 0;

    Outgoing* findOutgoing(uint16_t id);
};

}  // namespace pw::net
