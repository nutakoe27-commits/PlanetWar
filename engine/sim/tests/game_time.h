// Игровое время в тестах симуляции: секунды вместо тиков и огрублённый шаг.
//
// ЗАЧЕМ ЭТОТ ЗАГОЛОВОК СУЩЕСТВУЕТ.
//
// Единица действия в игре — ЧАС (см. pw/sim/schedule.h, раздел «ЧАСЫ ИГРЫ»).
// Скромная осада идёт четырнадцать часов, оборона отрастает двадцать один час,
// линкор строится семнадцать. На обычном шаге это полмиллиона тиков ради
// одной проверки, и набор тестов, отсчитывающий их по одному, идёт минуты.
// Набор тестов, который идёт минуты, перестают запускать между правками —
// а тест, который не запускают, ничего не проверяет.
//
// Поэтому тесты симуляции работают на СЖАТОМ шаге (SimTempo): один тик
// проживает одну игровую секунду вместо десятой доли. Все длительности в игре
// выражены в игровых секундах, а не в тиках, поэтому пропорции сохраняются
// точно, и проверяемые пороги — пала планета или устояла, отросла оборона
// или нет, достроилось здание или ещё нет — от шага не зависят.
//
// ЧТО СЖАТИЕ НЕ ПРОВЕРЯЕТ: точность самого шага. Её проверяет отдельный тест
// в test_schedule.cpp, который прогоняет один и тот же мир обычным и сжатым
// шагом и требует совпадения. Без него сжатие было бы удобным способом
// не заметить ошибку.
//
// СРОКИ ЗДЕСЬ НЕ ЗАПИСАНЫ ЧИСЛАМИ. Ниже есть функции, считающие ожидаемую
// длительность из тех же констант, что и сама игра. Тест, в котором написано
// «шахта строится 1500 секунд», ломается при каждой перенастройке баланса
// и чинится подгонкой числа — то есть перестаёт проверять что бы то ни было.
// Тест, в котором написано «шахта строится buildSeconds(Mine)», проверяет
// СВЯЗЬ цены со сроком, и она обязана держаться при любом балансе.
#pragma once

#include <cstdint>

#include "pw/sim/economy.h"
#include "pw/sim/fleet.h"
#include "pw/sim/production.h"
#include "pw/sim/schedule.h"

namespace pw::test {

/// Сжатие времени для тестов: один тик — одна игровая секунда.
inline constexpr int64_t kTestTempo = pw::sim::kTicksPerSecond;

// Единицы игрового времени. Тесты считают в них, а не в тиках.
inline constexpr int64_t kSecond = 1;
inline constexpr int64_t kMinute = 60 * kSecond;
inline constexpr int64_t kHour = 60 * kMinute;

/// Сколько тиков занимают столько-то игровых секунд на тестовом шаге.
inline int64_t testTicks(int64_t seconds) {
    return pw::sim::ticksForSeconds(seconds, kTestTempo);
}

/// Контекст шага теста. Через фабрику: шаг и сжатие обязаны быть согласованы.
inline pw::sim::TickContext testTick(int64_t index) {
    return pw::sim::TickContext::at(uint64_t(index), kTestTempo);
}

/// Сколько игровых секунд строится здание. Считается из цены той же
/// формулой, что и в игре, — значит проверяет связь, а не запомненное число.
inline int64_t buildSeconds(pw::sim::Building building) {
    return int64_t(pw::sim::buildingCost(building)) * pw::sim::kBuildSecondsPerMineral;
}

/// Сколько игровых секунд столько-то верфей собирают один корпус.
///
/// Верфь осваивает kBuildRateShipyard сплавов в секунду, корабль стоит
/// hullCost. Формула ровно та же, что в systemProduction.
inline int64_t hullSeconds(pw::sim::Hull hull, int64_t shipyards) {
    if (shipyards <= 0) return 0;
    const fx rate = pw::sim::kBuildRateShipyard * fx::fromInt(shipyards);
    if (rate <= fx::zero()) return 0;
    return (fx::fromInt(int64_t(pw::sim::hullCost(hull))) / rate).floorToInt() + 1;
}

}  // namespace pw::test
