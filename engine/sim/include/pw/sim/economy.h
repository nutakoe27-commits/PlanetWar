// Учёт по империям
// ---------------------------------------------------------------------------

/// Итоги тика по каждой империи.
///
/// Считается в отдельный буфер, а не пишется в империи по ходу обхода.
/// Причина — правило детерминизма: обход планет читает общие данные и копит
/// результат у себя, а применение идёт после барьера строго по возрастанию
/// номера империи. Иначе порядок обхода начал бы влиять на результат.
class Ledger {
public:
    struct Flow {
        fx energy, minerals, alloys, research, influence;
        /// Сколько сплавов не выплавлено из-за нехватки минералов.
        /// Показывается игроку: это главный сигнал «достройте шахты».
        fx foundryIdle;
    };

    void reset(uint32_t empires);
    Flow& at(uint32_t empire) { return flows_[empire]; }
    const Flow& at(uint32_t empire) const { return flows_[empire]; }
    uint32_t size() const { return uint32_t(flows_.size()); }

private:
    std::vector<Flow> flows_;
};

