/// Сколько слотов на планете доступно с учётом хабитатов.
///
/// Отдельной функцией, а не полем: число слотов планеты — свойство мира
/// и не меняется никогда, а хабитаты игрок строит и сносит. Держать сумму
/// в компоненте значило бы иметь два источника правды и однажды их развести.
uint8_t usableSlots(const Planet& planet, const PlanetDevelopment& development);

/// Сколько зданий данного вида стоит на планете.
uint8_t countBuildings(const Planet& planet, const PlanetDevelopment& development,
                       Building building);

/// Производит ли здание ресурсы. Ложь — значит оно покупает не доход,
/// а устойчивость: снабжение, щит, док, место, гарнизон.
bool isInfrastructure(Building building);

/// Совпадает ли здание со специализацией планеты.
bool matchesSpecialisation(Building building, Specialization specialisation);

/// Подходит ли класс планеты под здание.
bool matchesClass(Building building, uint8_t planetClass);

/// Во сколько минералов обходится здание.
///
/// Цена задаёт и время стройки: она делится на kBuildRatePlanet. Держать
/// два независимых числа «цена» и «срок» значило бы дать им разойтись —
/// и получить дешёвое здание, которое строится дольше дорогого.
uint32_t buildingCost(Building building);

/// Сколько зданий заданного типа стоит в каждой системе.
/// Нужно тому, что остаётся системным: верфь обслуживает всю систему.
std::vector<uint32_t> countBuildingsPerSystem(World& world, Building building,
                                             uint32_t systemCount);

