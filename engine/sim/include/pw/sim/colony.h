// pw_sim — колонизация: как империя вырастает с одной планеты.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ЧАСТЬ ОСАДЫ.
//
// Захват и колонизация — разные ответы на разные вопросы, и смешивать их
// нельзя. Осада отвечает «как отнять у соседа»: она долгая, шумная, видна
// на карте и даёт жертве время позвать своих. Колонизация отвечает «как
// вырасти самому»: она мгновенна в момент высадки, но ей предшествует
// дорогой медленный корабль, который надо построить, довести и не потерять.
//
// Одна стоит времени под огнём, вторая — времени в пути. У них общий итог
// (планета стала вашей) и ничего общего в цене.
//
// ИМПЕРИЯ НАЧИНАЕТСЯ С ОДНОЙ ПЛАНЕТЫ.
//
// Раньше игрок получал всю родную систему целиком и первые полчаса просто
// застраивал выданное. Решений в этом нет: что построить — вопрос, но КУДА
// расти вопросом не был, потому что расти было некуда и незачем.
//
// Теперь у него один мир и соседи-пустышки вокруг. Первое настоящее решение
// принимается на второй минуте: колонизатор стоит как два с половиной
// корвета, и это выбор между «ещё одна планета» и «чем её защищать».
#pragma once

#include <cstdint>

#include "pw/core/fixed.h"
#include "pw/sim/fleet.h"
#include "pw/sim/world.h"

namespace pw::sim {

class Galaxy;

/// С какой готовностью обороны рождается колония.
///
/// Низкая и НЕ НУЛЕВАЯ. Ноль означал бы, что свежая колония берётся
/// мимоходом любым проходящим корветом, и колонизация в спорных областях
/// теряла бы смысл вовсе. Четверть потолка — это примерно четверть часа
/// осады: достаточно, чтобы хозяин успел заметить и прийти.
inline const fx kColonyStartReadiness = fx::fromInt(25);

/// Почему колонизация не состоялась.
///
/// Перечислением, а не «истина/ложь»: игроку показывают ПРИЧИНУ, и она
/// разная. «Нет колонизатора» и «планета уже занята» — это два совершенно
/// разных следующих действия, а одинаковое «нельзя» заставляет гадать.
enum class ColonyRefusal : uint8_t {
    Ok = 0,
    /// Флот чужой или не существует.
    NotYours,
    /// Планета уже кому-то принадлежит. Такие берут осадой, а не высадкой.
    PlanetTaken,
    /// Флот в другой системе.
    WrongSystem,
    /// Флот в пути. Высаживаться на ходу нельзя: колонизация — это
    /// остановка и разгрузка, а не пролёт мимо.
    InTransit,
    /// Во флоте нет ни одного колонизатора.
    NoColonizer,
    Count
};

/// Человеческое объяснение отказа. Одна строка, для подсказки на кнопке.
const char* colonyRefusalText(ColonyRefusal refusal);

/// Можно ли этому флоту занять эту планету.
///
/// Чистая функция от состояния: ни мир, ни флот она не меняет. Поэтому
/// её зовут дважды и в двух разных местах — сервер перед выполнением
/// приказа и клиент перед показом кнопки, — и оба получают один ответ.
/// Кнопка, которая гаснет по той же причине, по которой сервер отказал,
/// не требует объяснений после нажатия.
ColonyRefusal colonizeCheck(uint32_t fleetEmpire, const Fleet& composition,
                            const FleetLocation& location, uint32_t planetEmpire,
                            uint32_t planetSystem);

/// Высадить колонию: списать один колонизатор и отдать планету империи.
///
/// Проверку НЕ делает — её делает вызывающий, потому что только он знает,
/// что сказать игроку при отказе. Здесь остаётся само действие, и оно
/// одинаково у сервера, у бота и у теста.
void applyColonize(Fleet& composition, uint32_t& planetEmpire, fx& planetReadiness,
                   uint32_t empire);

}  // namespace pw::sim
