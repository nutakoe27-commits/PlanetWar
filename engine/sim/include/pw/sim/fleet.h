/// Продвинуть флоты по маршрутам.
///
/// Берёт граф из ресурсов мира. Без графа тихо ничего не делает — это
/// нормально для тестов, где движения нет.
void systemFleetMovement(World& world, const TickContext& context);

/// Слить стоящие рядом РЕЗЕРВЫ одной империи с одинаковым вооружением.
///
/// Без слияния вообще каждый построенный корабль остаётся отдельным
/// отрядом: прогон сезона за шесть часов набрал 98 отрядов по одному
/// кораблю. Это плохо и для игрока — управлять сотней значков невозможно, —
/// и для сервера: каждый отряд обходится каждый тик и участвует в сведении
/// боёв.
///
/// НО СЛИЯНИЕ ОБЯЗАНО БЫТЬ УСЛОВНЫМ. Пока сливался КАЖДЫЙ стоящий отряд
/// без приказа, два своих отряда нельзя было держать раздельно дома:
/// выделил рейдовую группу — на следующем тике она снова в общей куче.
/// Одно это правило делало управление флотом в духе RTS невозможным.
///
/// Поэтому сливаются только отряды в стойке «Резерв» — те, которым игрок
/// не отдавал ни одного приказа. Построенный корабль попадает туда сам
/// и честно вливается в общий пул; тронутый игроком отряд не сливается
/// никогда.
///
/// Флоты с РАЗНЫМ вооружением не сливаются и здесь: смешав их, мы
/// потеряли бы выбор игрока, а вместе с ним и контр-систему.
void systemMergeFleets(World& world, const TickContext& context);

/// Решить, что делают отряды, которым нечего делать.
///
/// Идёт ПОСЛЕ присутствия (systemPresence) и ДО движения: уклонение
/// смотрит, кто ещё стоит в системе, а возврат домой обязан начаться
/// в том же тике, в котором маршрут кончился, — иначе кадр между ними
/// показывает отряд, который «уже дома, но ещё идёт».
void systemFleetStance(World& world, const TickContext& context);

/// Во сколько раз противник должен превосходить, чтобы уклоняющийся отряд
/// ушёл без боя.
///
/// Полтора. Не круглое число, а порог, при котором бой заведомо проигран:
/// боевая модель при таком перевесе не оставляет шансов, и стоять там
/// незачем. Ниже порога отряд дерётся — иначе «уклоняться» означало бы
/// «никогда не воевать», то есть кнопку «выключить флот».
inline constexpr uint32_t kEvadeNumerator = 3;
inline constexpr uint32_t kEvadeDenominator = 2;

/// Зарегистрировать компоненты флотов.
///
/// Вызывается ПОСЛЕ registerGalaxyComponents: порядок регистрации задаёт
/// идентификаторы, а те входят в хеш мира.
void registerFleetComponents(World& world);

