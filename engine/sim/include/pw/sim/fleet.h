/// «Никуда» — и для системы, и для цели приказа.
inline constexpr uint32_t kNoSystem = 0xFFFFFFFFu;

/// Класс корпуса.
///
/// ДВЕ ЛЕСТНИЦЫ, А НЕ ОДНА. Корвет — эсминец — крейсер — линкор — титан
/// это лестница РАЗМЕРА: дороже, прочнее, больше пушек, медленнее. Одной
/// её мало: когда все корпуса отличаются только величиной, «правильный»
/// флот всегда состоит из самого дорогого, что игрок может себе позволить,
/// и никакого решения нет — есть только счёт в банке.
///
/// Поэтому есть вторая лестница — РОЛЕЙ. Тендер не стреляет вообще, но
/// снижает потери всего отряда. Носитель бьёт с любой дистанции, зато его
/// машины сбивает ПРО. Монитор посредственен в бою и вдвое ускоряет осаду
/// планеты. Ни один из них не «лучше» линкора и не «хуже» — они отвечают
/// на другой вопрос.
///
/// ПОРЯДОК ВАЖЕН: он идёт строго по возрастанию цены. Потери в бою
/// списываются с дешёвых корпусов первыми (`survivors`), и порядок в этом
/// перечислении — это и есть порядок «кого не жалко». Вставите новый
/// корпус не на своё место — эскорт начнёт гибнуть позже линкоров.
/// ТРЕТЬЯ ЛЕСТНИЦА — ГРАЖДАНСКАЯ. Колонизатор не воюет вообще: он
/// единственный способ занять ничью планету, и в этом весь его смысл.
///
/// Место в перечислении он получил ПО ЦЕНЕ, как и все остальные, и это
/// оказалось ровно тем, что нужно. Порядок здесь — это порядок «кого
/// не жалко»: сначала гибнут корветы и тендеры, и только потом
/// колонизатор. То есть ЭСКОРТ РАБОТАЕТ — прикрытие честно принимает
/// на себя удар, а колонизатор без прикрытия гибнет сразу.
///
/// Сначала я поставил его первым, рассудив, что гражданское судно должно
/// гибнуть раньше всех. Тест, проверяющий возрастание цены, покраснел —
/// и был прав: при таком порядке эскорт не защищал бы никого, потому
/// что колонизатор погибал бы раньше собственного прикрытия.
enum class Hull : uint8_t {
    None = 0,
    Corvette,     // эскорт: дёшев, быстр, принимает на себя потери
    Tender,       // тендер: не стреляет, снижает потери отряда
    Colonizer,    // колонизатор: не стреляет, занимает ничью планету
    Destroyer,    // рабочая лошадь линии
    Carrier,      // носитель: ударные машины бьют с любой дистанции
    Cruiser,      // тяжёлый корабль линии
    Monitor,      // монитор: осадный, вдвое быстрее ломает оборону планеты
    Battleship,   // линкор: концентрация огня
    Titan,        // титан: венец сезона, требует верфи И ремонтного дока
    Count
};

/// Сколько классов корпусов существует, не считая None.
inline constexpr size_t kHullClasses = size_t(Hull::Count) - 1;

/// Состав флота. Отдельные корабли сущностями НЕ являются.
///
/// Это то самое решение, которое избавляет нас от замедления времени
/// при массовых боях (ADR-007): сражение стоит по числу флотов, а не по
/// числу кораблей, и бой на десять тысяч корветов обходится столько же,
/// сколько бой на десять.
///
/// МАССИВ, А НЕ ИМЕНОВАННЫЕ ПОЛЯ. Пока классов было четыре, четыре поля
/// читались лучше. С восемью каждый обход превращался в таблицу-костыль
/// вида `{0, fleet.corvettes, fleet.destroyers, ...}`, которую надо было
/// не забыть поправить в семи местах при добавлении корпуса. Забыли бы
/// в одном — новый класс тихо не считался бы в бою.
struct Fleet {
    uint32_t ships[kHullClasses];

    uint32_t& operator[](Hull hull) { return ships[size_t(hull) - 1]; }
    uint32_t operator[](Hull hull) const { return ships[size_t(hull) - 1]; }
};
static_assert(sizeof(Fleet) == kHullClasses * 4, "структура обязана быть без дыр");

/// Флот из перечисленных пар «класс — сколько».
///
/// Именно так, а не `Fleet{4, 0, 0, 0}`. Позиционная запись читалась, пока
/// классов было четыре и их порядок помнился наизусть. С восемью она стала
/// ловушкой: тот же `Fleet{4, 3, 0, ...}` тихо превратился бы из «четыре
/// корвета и три эсминца» в «четыре корвета и три ТЕНДЕРА», и ни один тест
/// этого бы не заметил — он бы просто начал проверять не то.
inline Fleet makeFleet(std::initializer_list<std::pair<Hull, uint32_t>> ships) {
    Fleet fleet{};
    for (const auto& entry : ships) {
        if (entry.first == Hull::None || entry.first >= Hull::Count) continue;
        fleet[entry.first] += entry.second;
    }
    return fleet;
}

/// Стоимость корпуса в сплавах.
uint32_t hullCost(Hull hull);

/// Добавить корабли заданного класса к флоту.
void fleetAdd(Fleet& fleet, Hull hull, uint32_t count = 1);

/// Где флот находится.
///
/// Стоящий флот: system == nextSystem. Идущий: движется от system к
/// nextSystem, progress — пройденная доля линии.
struct FleetLocation {
    uint32_t system;
    uint32_t nextSystem;
    /// Возле какой планеты системы стоит флот, по порядку от звезды.
    /// kNoOrbit — на общей стоянке или в пути.
    ///
    /// ЗАЧЕМ ФЛОТУ ОРБИТА. Система — это не точка, а четыре-пять миров,
    /// и «флот в системе» ничего не говорит о том, что он там делает.
    /// Флот, стоящий у конкретной планеты, читается с одного взгляда:
    /// это гарнизон вот этого мира. Отсюда потом вырастает и оборона
    /// планеты своим флотом, и блокада чужой, и очередь на верфи —
    /// но сначала нужна сама привязка.
    ///
    /// Живёт в симуляции, а не в клиенте: это состояние мира, одинаковое
    /// у всех, а не украшение экрана. Клиент, придумывающий орбиты сам,
    /// показывал бы двум игрокам разное.
    uint32_t orbit;
    uint32_t reserved;
    fx progress;
};
static_assert(sizeof(FleetLocation) == 24, "структура обязана быть без дыр");

/// «Флот не привязан ни к какой планете».
inline constexpr uint32_t kNoOrbit = 0xFFFFFFFFu;

/// Стоящий флот в системе. По той же причине, что и `makeFleet`:
/// позиционные скобки `FleetLocation{s, s, fx::zero()}` читались, пока
/// полей было три. С добавлением орбиты они молча начали бы класть
/// прогресс в номер планеты — и это тот самый вид ошибки, который
/// компилятор ловит не всегда, а тест не ловит вовсе.
inline FleetLocation standingAt(uint32_t system, uint32_t orbit = kNoOrbit) {
    return FleetLocation{system, system, orbit, 0, fx::zero()};
}

/// Флот в пути между узлами.
inline FleetLocation inTransit(uint32_t from, uint32_t to, fx progress) {
    return FleetLocation{from, to, kNoOrbit, 0, progress};
}

/// Приказ на перемещение.
///
/// Хранится только конечная цель, не весь маршрут. Следующий шаг флот
/// пересчитывает в момент прибытия в узел: так компонент остаётся
/// фиксированного размера, а приказ переживает изменение карты — например,
/// разрушенную гиперлинию или новые звёздные врата.
///
/// target == kNoSystem означает «приказа нет». Так снятие приказа не меняет
/// набор компонентов и не переносит сущность между таблицами — а значит,
/// его можно делать прямо в обходе.
struct MoveOrder {
    uint32_t target;
    uint32_t reserved;
};
static_assert(sizeof(MoveOrder) == 8, "структура обязана быть без дыр");

// ---------------------------------------------------------------------------
// Скорости корпусов, игровых единиц в секунду
//
// Игровая секунда равна реальной: горячие системы тикают 10 раз в секунду.
// Поэтому время пролёта — это буквально время, которое ждёт игрок, и числа
// здесь подобраны от требований дизайна, а не от ощущения.
//
// Замер на карте из 500 систем: радиус 1200 единиц, средняя гиперлиния около
// 90 единиц, диаметр карты 26 прыжков и примерно 2300 единиц пути.
//
//   линкор     1.0 ед/с  ->  линия за полторы минуты, галактика за ~38 минут
//   крейсер    1.4
//   эсминец    1.8
//   корвет     2.3 ед/с  ->  галактика за ~17 минут
//
// Первая версия ставила 26–60 единиц в секунду, и линейный флот пересекал
// галактику за полторы минуты. При таких скоростях не работает НИЧЕГО из
// того, на чём стоит дизайн: ни логистика, ни специализация регионов, ни
// перехват конвоев, ни осада длиной в полчаса — подкрепление успевало бы
// прийти откуда угодно раньше, чем осада началась.
//
// Обнаружено инструментом предпросмотра карты, а не тестом: тесты проверяли
// отношение скоростей между классами, и оно было верным. Неверен был масштаб.
//
// На Фазе 3 уедут в таблицу баланса (ADR-010) — формат полей уже совпадает.
// ---------------------------------------------------------------------------

/// Колонизатор медленный: он везёт людей и оборудование, а не пушки.
/// Медленный колонизатор превращает расширение в РЕШЕНИЕ — куда именно
/// потратить эти пять минут, — а не в щелчок по ближайшей свободной точке.
inline const fx kSpeedColonizer = fx::fromFraction(11, 10);
inline const fx kSpeedCorvette = fx::fromFraction(23, 10);
inline const fx kSpeedTender = fx::fromFraction(19, 10);
inline const fx kSpeedDestroyer = fx::fromFraction(18, 10);
inline const fx kSpeedCarrier = fx::fromFraction(13, 10);
inline const fx kSpeedCruiser = fx::fromFraction(14, 10);
/// Монитор — самоходная батарея, а не корабль линии. Он медленнее линкора
/// намеренно: осадный флот обязан идти к цели заметно дольше ударного,
/// иначе осада перестаёт быть операцией, которую готовят, и становится
/// первым, что делает любой флот при встрече с планетой.
inline const fx kSpeedMonitor = fx::fromFraction(8, 10);
inline const fx kSpeedBattleship = fx::fromInt(1);
inline const fx kSpeedTitan = fx::fromFraction(7, 10);

/// Скорость корпуса. Скорость флота — минимум по присутствующим классам.
fx hullSpeed(Hull hull);

/// Поставить стоящие флоты на орбиты планет. Идёт СРАЗУ ЗА движением:
/// флот, только что прибывший в систему, обязан получить орбиту в том же
