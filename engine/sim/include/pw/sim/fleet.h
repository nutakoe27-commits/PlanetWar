void systemFleetStation(World& world, const TickContext& context);

// ---------------------------------------------------------------------------
// Стоимость корпусов в сплавах
//
// Числа привязаны к осаде, а не выбраны на глаз. Опорное соотношение:
// РАЗВИТАЯ СИСТЕМА СТРОИТ ЛИНКОР ПРИМЕРНО ЗА ВРЕМЯ ОДНОЙ ОСАДЫ.
//
// Замер: четыре шахты и четыре завода дают 45 сплавов в минуту, осада длится
// 33–65 минут. Отсюда линкор в 2400 сплавов — около 53 минут.
//
// Что это даёт:
//   молодая колония (12/мин) — корвет за 8 мин, линкор за 3 часа. Линкоры
//                              недоступны, и это правильно: их надо заслужить;
//   развитая система (45/мин) — корвет за 2 мин, линкор за 53. Потеря линкора
//                              стоит целой осады, поэтому потери значат что-то;
//   промышленный узел (90/мин) — линкор за 27 мин. Специализация окупается.
//
// Первая версия ставила стоимости вчетверо ниже, и развитая система выдавала
// линкор за 13 минут — под сорок штук за игровой день с ОДНОЙ системы.
// При таких числах потери перестают что-либо значить, а вместе с ними теряет
// смысл и износ флота, и вся идея, что войну надо готовить.
//
// Цена за единицу тоннажа растёт с классом: 100, 107, 112, 120. Это плата за
// концентрацию силы в одной цели, и она же оставляет смысл дешёвому
// массовому флоту.
//
// На Фазе 3 уедут в таблицу баланса (ADR-010).
// ---------------------------------------------------------------------------

/// Колонизатор дороже корвета, но дешевле эсминца.
///
/// Цена — это и есть скорость расширения, главный регулятор всей партии.
/// Дешёвый колонизатор превращает Расширение в гонку кликов: кто быстрее
/// нажал, тот и взял полкарты. Дорогой — заставляет выбирать между
/// «ещё одна планета» и «ещё один корабль», а это и есть стратегия.
inline constexpr uint32_t kCostColonizer = 240;
inline constexpr uint32_t kCostCorvette = 100;
inline constexpr uint32_t kCostTender = 180;
inline constexpr uint32_t kCostDestroyer = 320;
inline constexpr uint32_t kCostCarrier = 760;
inline constexpr uint32_t kCostCruiser = 900;
inline constexpr uint32_t kCostMonitor = 1200;
inline constexpr uint32_t kCostBattleship = 2400;
/// Титан стоит четырёх линкоров и требует верфи И ремонтного дока.
///
/// Он и должен быть недостижим для большинства: венец сезона, который
/// строит одна система империи за час, — это цель, ради которой строят
/// инфраструктуру. Дешёвый титан превратился бы в обязательную покупку,
/// то есть в налог, а не в решение.
inline constexpr uint32_t kCostTitan = 9600;

/// Полная стоимость флота в сплавах.
uint32_t fleetCost(const Fleet& fleet);

// ---------------------------------------------------------------------------
// Выделение кораблей из флота
//
// ЗАЧЕМ ЭТО НУЖНО. Флоты в системе сливаются в один — это правило держит
// число сущностей в узде и избавляет от микроменеджмента. Но у слияния
// есть цена: как только у игрока появился колонизатор, он оказывается
// в общей куче с боевым флотом и уходит воевать вместе с ним.
//
// Выделение — обратная операция, и она обязана быть ДЕШЁВОЙ по действиям:
// один щелчок по классу корабля. Иначе игрок просто не станет разделять
// флот, и вся механика колонизации сведётся к «строю колонизатор ровно
// тогда, когда флот стоит дома».
// ---------------------------------------------------------------------------

/// Почему выделить не вышло.
enum class SplitRefusal : uint8_t {
    Ok = 0,
    /// Флот чужой или не существует.
    NotYours,
    /// Флот в пути: перестраиваться на ходу нельзя.
    InTransit,
    /// Столько кораблей этого класса во флоте нет.
    NotEnough,
    /// Выделить ВЕСЬ флот — это не выделение, а переименование.
    WholeFleet,
    Count
};

const char* splitRefusalText(SplitRefusal refusal);

/// Можно ли выделить `count` кораблей класса `hull` из этого флота.
SplitRefusal splitCheck(const Fleet& composition, const FleetLocation& location,
                        Hull hull, uint32_t count);

/// Выделить корабли: вычесть их из исходного флота и вернуть состав нового.
/// Проверку не делает — её делает вызывающий, потому что только он знает,
/// что сказать игроку при отказе.
Fleet applySplit(Fleet& composition, Hull hull, uint32_t count);

/// Осадная мощь флота: сколько «условных мониторов» он стоит при штурме.
///
/// Отдельно от боевой силы, потому что это ДРУГАЯ работа. Флот из ста
/// корветов выигрывает сражение и почти не двигает осаду; три монитора
/// проигрывают любому бою и ломают оборону планеты вдвое быстрее.
/// Разделение этих двух чисел и делает осадный флот отдельным решением.
uint32_t fleetSiegePower(const Fleet& fleet);

/// Доля потерь, которую отряд не понесёт благодаря тендерам.
///
/// Тендер не стреляет вообще. Он покупается вместо пушки, и вопрос
/// «сколько тендеров взять» — это вопрос «сколько огня я готов отдать
/// за то, чтобы отряд вернулся». Потолок стоит намеренно: флот
/// из одних тендеров не должен становиться неуязвимым.
fx fleetDamageControl(const Fleet& fleet);

/// Скорость флота задаёт САМЫЙ МЕДЛЕННЫЙ корабль в нём.
///
/// Это не мелочь, а рычаг баланса: быстрый рейдовый отряд корветов ходит
/// вдвое быстрее линейного флота, поэтому перехват конвоев и оборона тыла
/// становятся отдельной ролью, а не побочным занятием линкоров.
fx fleetSpeed(const Fleet& fleet);

/// Пуст ли флот. Пустые флоты подлежат роспуску.
inline bool fleetEmpty(const Fleet& fleet) {
    for (size_t index = 0; index < kHullClasses; ++index) {
        if (fleet.ships[index] != 0) return false;
    }
    return true;
}

/// Сколько всего кораблей во флоте, без учёта класса.
inline uint32_t fleetShipCount(const Fleet& fleet) {
    uint32_t total = 0;
    for (size_t index = 0; index < kHullClasses; ++index) total += fleet.ships[index];
    return total;
}

/// Суммарный тоннаж. Идёт в подсчёт военных очков престижа и в оценку сил.
uint32_t fleetTonnage(const Fleet& fleet);

