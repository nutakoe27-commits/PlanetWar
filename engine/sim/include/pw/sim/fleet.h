/// Продвинуть флоты по маршрутам.
///
/// Берёт граф из ресурсов мира. Без графа тихо ничего не делает — это
/// нормально для тестов, где движения нет.
void systemFleetMovement(World& world, const TickContext& context);

/// Слить стоящие рядом флоты одной империи с одинаковым вооружением.
///
/// Без этого каждый построенный корабль остаётся отдельным отрядом: прогон
/// сезона за шесть часов набрал 98 отрядов по одному кораблю. Это плохо
/// и для игрока — управлять сотней значков невозможно, — и для сервера:
/// каждый отряд обходится каждый тик и участвует в сведении боёв.
///
/// Флоты с РАЗНЫМ вооружением не сливаются: смешав их, мы потеряли бы
/// выбор игрока, а вместе с ним и контр-систему.
void systemMergeFleets(World& world, const TickContext& context);

