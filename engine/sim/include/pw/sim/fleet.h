/// «Никуда» — и для системы, и для цели приказа.
inline constexpr uint32_t kNoSystem = 0xFFFFFFFFu;

/// Класс корпуса.
///
/// ДВЕ ЛЕСТНИЦЫ, А НЕ ОДНА. Корвет — эсминец — крейсер — линкор — титан
/// это лестница РАЗМЕРА: дороже, прочнее, больше пушек, медленнее. Одной
/// её мало: когда все корпуса отличаются только величиной, «правильный»
/// флот всегда состоит из самого дорогого, что игрок может себе позволить,
/// и никакого решения нет — есть только счёт в банке.
///
/// Поэтому есть вторая лестница — РОЛЕЙ. Тендер не стреляет вообще, но
/// снижает потери всего отряда. Носитель бьёт с любой дистанции, зато его
/// машины сбивает ПРО. Монитор посредственен в бою и вдвое ускоряет осаду
/// планеты. Ни один из них не «лучше» линкора и не «хуже» — они отвечают
/// на другой вопрос.
///
/// ПОРЯДОК ВАЖЕН: он идёт строго по возрастанию цены. Потери в бою
/// списываются с дешёвых корпусов первыми (`survivors`), и порядок в этом
/// перечислении — это и есть порядок «кого не жалко». Вставите новый
/// корпус не на своё место — эскорт начнёт гибнуть позже линкоров.
/// ТРЕТЬЯ ЛЕСТНИЦА — ГРАЖДАНСКАЯ. Колонизатор не воюет вообще: он
/// единственный способ занять ничью планету, и в этом весь его смысл.
///
/// Место в перечислении он получил ПО ЦЕНЕ, как и все остальные, и это
/// оказалось ровно тем, что нужно. Порядок здесь — это порядок «кого
/// не жалко»: сначала гибнут корветы и тендеры, и только потом
/// колонизатор. То есть ЭСКОРТ РАБОТАЕТ — прикрытие честно принимает
/// на себя удар, а колонизатор без прикрытия гибнет сразу.
///
/// Сначала я поставил его первым, рассудив, что гражданское судно должно
/// гибнуть раньше всех. Тест, проверяющий возрастание цены, покраснел —
/// и был прав: при таком порядке эскорт не защищал бы никого, потому
/// что колонизатор погибал бы раньше собственного прикрытия.
enum class Hull : uint8_t {
    None = 0,
    Corvette,     // эскорт: дёшев, быстр, принимает на себя потери
    Tender,       // тендер: не стреляет, снижает потери отряда
    Colonizer,    // колонизатор: не стреляет, занимает ничью планету
    Destroyer,    // рабочая лошадь линии
    Carrier,      // носитель: ударные машины бьют с любой дистанции
    Cruiser,      // тяжёлый корабль линии
    Monitor,      // монитор: осадный, вдвое быстрее ломает оборону планеты
    Battleship,   // линкор: концентрация огня
    Titan,        // титан: венец сезона, требует верфи И ремонтного дока
    Count
};

/// Сколько классов корпусов существует, не считая None.
inline constexpr size_t kHullClasses = size_t(Hull::Count) - 1;

/// Состав флота. Отдельные корабли сущностями НЕ являются.
///
/// Это то самое решение, которое избавляет нас от замедления времени
/// при массовых боях (ADR-007): сражение стоит по числу флотов, а не по
/// числу кораблей, и бой на десять тысяч корветов обходится столько же,
/// сколько бой на десять.
///
/// МАССИВ, А НЕ ИМЕНОВАННЫЕ ПОЛЯ. Пока классов было четыре, четыре поля
/// читались лучше. С восемью каждый обход превращался в таблицу-костыль
/// вида `{0, fleet.corvettes, fleet.destroyers, ...}`, которую надо было
/// не забыть поправить в семи местах при добавлении корпуса. Забыли бы
/// в одном — новый класс тихо не считался бы в бою.
struct Fleet {
    uint32_t ships[kHullClasses];

    uint32_t& operator[](Hull hull) { return ships[size_t(hull) - 1]; }
    uint32_t operator[](Hull hull) const { return ships[size_t(hull) - 1]; }
};
static_assert(sizeof(Fleet) == kHullClasses * 4, "структура обязана быть без дыр");

/// Флот из перечисленных пар «класс — сколько».
///
/// Именно так, а не `Fleet{4, 0, 0, 0}`. Позиционная запись читалась, пока
/// классов было четыре и их порядок помнился наизусть. С восемью она стала
/// ловушкой: тот же `Fleet{4, 3, 0, ...}` тихо превратился бы из «четыре
/// корвета и три эсминца» в «четыре корвета и три ТЕНДЕРА», и ни один тест
/// этого бы не заметил — он бы просто начал проверять не то.
inline Fleet makeFleet(std::initializer_list<std::pair<Hull, uint32_t>> ships) {
    Fleet fleet{};
    for (const auto& entry : ships) {
        if (entry.first == Hull::None || entry.first >= Hull::Count) continue;
        fleet[entry.first] += entry.second;
    }
    return fleet;
}

/// Стоимость корпуса в сплавах.
uint32_t hullCost(Hull hull);

/// Добавить корабли заданного класса к флоту.
void fleetAdd(Fleet& fleet, Hull hull, uint32_t count = 1);

/// Где флот находится.
///
/// Стоящий флот: system == nextSystem. Идущий: движется от system к
/// nextSystem, progress — пройденная доля линии.
struct FleetLocation {
    uint32_t system;
    uint32_t nextSystem;
    /// Возле какой планеты системы стоит флот, по порядку от звезды.
    /// kNoOrbit — на общей стоянке или в пути.
    ///
    /// ЗАЧЕМ ФЛОТУ ОРБИТА. Система — это не точка, а четыре-пять миров,
    /// и «флот в системе» ничего не говорит о том, что он там делает.
    /// Флот, стоящий у конкретной планеты, читается с одного взгляда:
    /// это гарнизон вот этого мира. Отсюда потом вырастает и оборона
    /// планеты своим флотом, и блокада чужой, и очередь на верфи —
    /// но сначала нужна сама привязка.
    ///
    /// Живёт в симуляции, а не в клиенте: это состояние мира, одинаковое
    /// у всех, а не украшение экрана. Клиент, придумывающий орбиты сам,
    /// показывал бы двум игрокам разное.
    uint32_t orbit;
    uint32_t reserved;
    fx progress;
};
static_assert(sizeof(FleetLocation) == 24, "структура обязана быть без дыр");

/// «Флот не привязан ни к какой планете».
inline constexpr uint32_t kNoOrbit = 0xFFFFFFFFu;

/// Стоящий флот в системе. По той же причине, что и `makeFleet`:
/// позиционные скобки `FleetLocation{s, s, fx::zero()}` читались, пока
/// полей было три. С добавлением орбиты они молча начали бы класть
/// прогресс в номер планеты — и это тот самый вид ошибки, который
/// компилятор ловит не всегда, а тест не ловит вовсе.
inline FleetLocation standingAt(uint32_t system, uint32_t orbit = kNoOrbit) {
    return FleetLocation{system, system, orbit, 0, fx::zero()};
}

/// Флот в пути между узлами.
inline FleetLocation inTransit(uint32_t from, uint32_t to, fx progress) {
    return FleetLocation{from, to, kNoOrbit, 0, progress};
}

// ---------------------------------------------------------------------------
// Приказы отряду
//
// ГЛАВНОЕ ПРАВИЛО ЭТОГО РАЗДЕЛА: КАЖДЫЙ ПРИКАЗ ОБЯЗАН ПЕРЕЖИТЬ НОЧЬ.
//
// Линия занимает у линкора девятнадцать минут, осада идёт четырнадцать
// часов, игрок девять десятых времени не в игре. Приказ, требующий
// вернуться через пять минут, — это не приказ, а таймер на живого
// человека. Отсюда и маршрут вместо одной цели, и стойки: игрок один раз
// говорит, что делать, и уходит.
//
// Полное обоснование — docs/08-FLEET-COMMAND.md.
// ---------------------------------------------------------------------------

/// Что отряд делает САМ, когда маршрут кончился или его не было.
///
/// Не «режим интерфейса», а состояние мира: сервер считает по нему
/// поведение флота, пока игрока нет.
enum class Stance : uint8_t {
    /// Резерв: игрок этот отряд не трогал. Только резервы сливаются
    /// друг с другом — см. systemMergeFleets.
    Reserve = 0,
    /// Стоять там, где встал. Ничего не делает по своей воле.
    Hold,
    /// Охранять приписку: когда делать нечего — возвращаться домой.
    Guard,
    /// Патруль: маршрут не кончается, а начинается заново.
    Patrol,
    Count
};

const char* stanceName(Stance stance);
/// Одна строка: что эта стойка означает для игрока.
const char* stanceHint(Stance stance);

/// Приказы отряда: маршрут, стойка, приписка, номер.
///
/// ХРАНЯТСЯ ЦЕЛИ, А НЕ РЁБРА. Следующий прыжок флот пересчитывает
/// в момент прибытия в узел: так компонент остаётся фиксированного
/// размера, а маршрут переживает изменение карты — разрушенную линию,
/// новые звёздные врата.
///
/// Пустой маршрут (count == 0) означает «приказа нет». Так снятие приказа
/// не меняет набор компонентов и не переносит сущность между таблицами,
/// а значит, его можно делать прямо в обходе.
struct FleetOrders {
    /// Сколько точек помещается в маршрут.
    ///
    /// Восемь. Диаметр карты — 26 прыжков, но маршрут длиннее восьми
    /// точек это уже не план, а программа: столько шагов вперёд человек
    /// не удерживает и всё равно переотдаёт приказ по дороге. Восемь
    /// покрывают любую осмысленную операцию и оставляют компонент
    /// в 48 байтах.
    static constexpr uint8_t kMaxRoute = 8;

    uint32_t route[kMaxRoute];
    /// Система приписки: дом отряда. Туда он возвращается в стойке
    /// «Охранять» и оттуда не уходит по своей воле.
    uint32_t anchor;
    /// Планета приписки или kNoOrbit — «вся система». Стоя дома, отряд
    /// занимает именно эту орбиту: так гарнизон конкретного мира читается
    /// с одного взгляда.
    uint32_t anchorOrbit;
    /// Номер отряда в империи, начиная с единицы. Ноль — «без номера».
    ///
    /// Номер, а не имя. Строки по сети — отдельная задача с длиной,
    /// фильтрацией и локализацией; номер решает ту же задачу за два
    /// байта. «Третий» отличается от «пятого» ничем не хуже имени.
    uint16_t tag;
    uint8_t stance;
    /// Какая точка маршрута сейчас цель. step >= count — маршрут кончился.
    uint8_t step;
    uint8_t count;
    /// Уклоняться ли от превосходящего противника.
    ///
    /// Признак отдельно от стойки намеренно: уклоняться может и патруль,
    /// и охрана, и просто стоящий отряд. Смешав его со стойкой, мы
    /// получили бы восемь стоек вместо четырёх и ни одной новой мысли.
    uint8_t evade;
    uint16_t reserved;

    /// Куда отряд идёт прямо сейчас. kNoSystem — никуда.
    uint32_t target() const { return step < count ? route[step] : kNoSystem; }
    /// Есть ли действующий маршрут.
    bool routed() const { return step < count; }
};
static_assert(sizeof(FleetOrders) == 48, "структура обязана быть без дыр");

/// Отряд без маршрута, приписанный сюда же.
inline FleetOrders idleOrders(uint32_t anchor, uint32_t orbit = kNoOrbit,
                              uint16_t tag = 0, Stance stance = Stance::Reserve) {
    FleetOrders orders{};
    for (uint8_t i = 0; i < FleetOrders::kMaxRoute; ++i) orders.route[i] = kNoSystem;
    orders.anchor = anchor;
    orders.anchorOrbit = orbit;
    orders.tag = tag;
    orders.stance = uint8_t(stance);
    return orders;
}

/// Снять маршрут. Стойку и приписку не трогает: это разные решения.
void clearRoute(FleetOrders& orders);

/// Задать маршрут из одной точки, заменив прежний.
void setRoute(FleetOrders& orders, uint32_t system);

/// Добавить точку в конец маршрута.
///
/// false — маршрут полон. Молчаливый отказ был бы худшим исходом: игрок
/// щёлкает, ничего не происходит, и понять почему неоткуда.
bool appendRoute(FleetOrders& orders, uint32_t system);

/// Отметить, что игрок отдал этому отряду приказ.
///
/// ПЕРВЫЙ ЖЕ ПРИКАЗ ВЫВОДИТ ОТРЯД ИЗ РЕЗЕРВА. Без этого правила игрок
/// отправлял бы рейдовую группу на передовую базу и обнаруживал, что она
/// растворилась в тамошнем гарнизоне: резервы сливаются, а «резерв» —
/// это в точности «корабли, которых я не трогал».
void commandGiven(FleetOrders& orders);

// ---------------------------------------------------------------------------
// Скорости корпусов, игровых единиц в секунду
//
// Игровая секунда равна реальной: горячие системы тикают 10 раз в секунду.
// Поэтому время пролёта — это буквально время, которое ждёт игрок, и числа
// здесь подобраны от требований дизайна, а не от ощущения.
//
// Замер на карте из 500 систем: радиус 1200 единиц, средняя гиперлиния около
// 90 единиц, диаметр карты 26 прыжков и примерно 2300 единиц пути.
//
//   линкор     0.080 ед/с  ->  линия за 19 минут, галактика за 8 часов
//   крейсер    0.112       ->  линия за 13 минут
//   эсминец    0.144
//   корвет     0.184 ед/с  ->  линия за 8 минут, галактика за 3.5 часа
//   титан      0.056 ед/с  ->  линия за 27 минут, галактика за 11.5 часов
//
// ДВА ИСПРАВЛЕНИЯ МАСШТАБА, и второе важнее первого.
//
// Первая версия ставила 26–60 единиц в секунду, и линейный флот пересекал
// галактику за полторы минуты. При таких скоростях не работает НИЧЕГО из
// того, на чём стоит дизайн: ни логистика, ни специализация регионов, ни
// перехват конвоев — подкрепление успевало бы прийти откуда угодно раньше,
// чем осада началась. Обнаружено инструментом предпросмотра карты, а не
// тестом: тесты проверяли отношение скоростей между классами, и оно было
// верным. Неверен был масштаб.
//
// Вторая версия ставила 1–2.3 единицы и мерила путь МИНУТАМИ. Это было
// верно для сезона длиной в два часа и неверно для сезона длиной
// в одиннадцать недель: переброска флота через галактику за полчаса —
// не решение, а рутина. Сейчас скорости в 12.5 раз меньше, и путь мерится
// ЧАСАМИ (см. pw/sim/schedule.h, «ЧАСЫ ИГРЫ»). Отношения между классами
// сохранены точно: менялся только масштаб, и оба раза он был главным.
//
// Что даёт часовой масштаб. Соседняя система — четверть часа: рейд можно
// провести за один сеанс. Другой конец галактики — восемь часов: это
// операция, которую планируют с вечера. Между этими двумя числами
// и живёт вся стратегия расположения флота.
//
// На Фазе 3 уедут в таблицу баланса (ADR-010) — формат полей уже совпадает.
// ---------------------------------------------------------------------------

/// Колонизатор медленный: он везёт людей и оборудование, а не пушки.
/// Медленный колонизатор превращает расширение в РЕШЕНИЕ — куда именно
/// потратить эти три часа пути, — а не в щелчок по ближайшей свободной
/// точке. Три часа, а не пять минут: расширение обязано стоить дня.
inline const fx kSpeedColonizer = fx::fromFraction(11, 125);
inline const fx kSpeedCorvette = fx::fromFraction(23, 125);
inline const fx kSpeedTender = fx::fromFraction(19, 125);
inline const fx kSpeedDestroyer = fx::fromFraction(18, 125);
inline const fx kSpeedCarrier = fx::fromFraction(13, 125);
inline const fx kSpeedCruiser = fx::fromFraction(14, 125);
/// Монитор — самоходная батарея, а не корабль линии. Он медленнее линкора
/// намеренно: осадный флот обязан идти к цели заметно дольше ударного,
/// иначе осада перестаёт быть операцией, которую готовят, и становится
/// первым, что делает любой флот при встрече с планетой.
inline const fx kSpeedMonitor = fx::fromFraction(8, 125);
inline const fx kSpeedBattleship = fx::fromFraction(10, 125);
inline const fx kSpeedTitan = fx::fromFraction(7, 125);

/// Скорость корпуса. Скорость флота — минимум по присутствующим классам.
fx hullSpeed(Hull hull);

/// Поставить стоящие флоты на орбиты планет. Идёт СРАЗУ ЗА движением:
/// флот, только что прибывший в систему, обязан получить орбиту в том же
/// тике, иначе кадр между прибытием и стоянкой показывает его нигде.
void systemFleetStation(World& world, const TickContext& context);

// ---------------------------------------------------------------------------
// Стоимость корпусов в сплавах
//
// Числа привязаны к осаде, а не выбраны на глаз. Опорное соотношение:
// РАЗВИТАЯ СИСТЕМА СТРОИТ ЛИНКОР ПРИМЕРНО ЗА ВРЕМЯ ОДНОЙ ОСАДЫ.
//
// Замер: четыре шахты и четыре завода дают 45 сплавов в минуту, осада длится
// 33–65 минут. Отсюда линкор в 2400 сплавов — около 53 минут.
//
// Что это даёт:
//   молодая колония (12/мин) — корвет за 8 мин, линкор за 3 часа. Линкоры
//                              недоступны, и это правильно: их надо заслужить;
//   развитая система (45/мин) — корвет за 2 мин, линкор за 53. Потеря линкора
//                              стоит целой осады, поэтому потери значат что-то;
//   промышленный узел (90/мин) — линкор за 27 мин. Специализация окупается.
//
// Первая версия ставила стоимости вчетверо ниже, и развитая система выдавала
// линкор за 13 минут — под сорок штук за игровой день с ОДНОЙ системы.
// При таких числах потери перестают что-либо значить, а вместе с ними теряет
// смысл и износ флота, и вся идея, что войну надо готовить.
//
