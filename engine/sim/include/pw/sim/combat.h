// pw_sim — разрешение боя.
//
// Бой считается сервером детерминированно, без присутствия игроков (ADR-007).
// Это не упрощение, а перенос состязания туда, где оно интереснее: в билд,
// доктрину и разведку.
//
// СТОИМОСТЬ. Бой работает с ЧИСЛАМИ кораблей, а не с кораблями как
// сущностями. Сражение тысячи корветов стоит столько же, сколько сражение
// десяти. Именно поэтому нам не понадобится замедление времени, которое EVE
// вынуждена включать при массовых боях.
//
// КОНТР-СИСТЕМА — сердце всей скилловой части игры:
//
//   кинетика  сильна против брони,  вязнет в щитах
//   энергия   сильна против щитов,  вязнет в броне
//   ракеты    игнорируют щиты,      сбиваются системами ПРО
//
// То есть у каждого вооружения есть своя защита-контра, и ни одна не бьёт
// всех. Знание состава противника позволяет меньшему флоту победить большего —
// ровно та ось, которая заменяет скорость мышки.
#pragma once

#include <cstdint>

#include "pw/core/fixed.h"
#include "pw/core/rng.h"
#include "pw/sim/fleet.h"

namespace pw::sim {

/// Доктрина боя. Выбирается игроком заранее и меняет ход сражения.
enum class Doctrine : uint8_t {
    /// Линия: максимум огня, минимум манёвра. Сходится быстро.
    Line = 0,
    /// Охват: заходит по флангам. Сходится медленнее, но бьёт больнее
    /// по тяжёлым корпусам, которым труднее развернуться.
    Envelop,
    /// Уклонение: принимает меньше урона, но и сходится дольше всех,
    /// поэтому дольше остаётся под ракетным огнём.
    Evasive,
    Count
};

/// Чем вооружён и как защищён флот.
///
/// Доли в процентах: как распределены оружейные, защитные и утилитарные слоты
/// кораблей. Это и есть конструктор кораблей, выраженный пропорциями, а не
/// поимённым списком слотов.
///
/// Компромисс осознанный: РЕШЕНИЕ игрока (чем вооружаться против кого)
/// сохранено полностью, а поимённый учёт каждого проекта корабля отложен
/// до Фазы 3, когда появится редактор и таблицы баланса.
struct FleetArmament {
    uint8_t kinetic;       // доля оружейных слотов, проценты
    uint8_t energy;
    uint8_t missile;
    uint8_t pointDefense;  // доля утилитарных слотов под ПРО
    uint8_t shields;       // доля защитных слотов под щиты
    uint8_t armour;        // ...под броню
    uint8_t doctrine;      // Doctrine — выбирается заранее, до встречи с врагом
    uint8_t reserved;
};
static_assert(sizeof(FleetArmament) == 8, "структура обязана быть без дыр");

/// Сбалансированное вооружение: поровну всего. Ни от чего не защищает
/// толком и ни против чего не силён — но и не проигрывает вчистую.
FleetArmament balancedArmament();

/// Сторона в сражении.
struct BattleSide {
    Fleet fleet;
    FleetArmament armament;
    Doctrine doctrine = Doctrine::Line;
    /// Сколько ремонтных доков этой империи стоит в системе боя.
    ///
    /// СВОЯ ТЕРРИТОРИЯ ОБЯЗАНА ЧТО-ТО ЗНАЧИТЬ. Наступающий и так сильнее
    /// просто потому, что выбирает момент и место: он приходит собранным
    /// кулаком к тому, кто размазан по фронту. Доки — противовес: рядом
    /// с ними повреждённые корабли чинят, а не списывают, и лезть в чужой
    /// тыл становится дороже, чем встретить противника в поле.
    uint32_t drydocks = 0;
};

/// Потолок суммарного снижения потерь от тендеров и доков вместе.
///
/// Без общего потолка флот из тендеров у своих доков стал бы неуязвимым,
/// и вся война свелась бы к тому, чтобы не выходить из дома.
inline const fx kDamageControlCap = fx::fromFraction(1, 2);
/// Насколько один док снижает потери своего флота в этой системе.
inline const fx kDrydockDamageControl = fx::fromFraction(3, 50);

/// Исход.
struct BattleResult {
    Fleet lossesA;      // кого потеряла сторона A
    Fleet lossesB;
    uint32_t rounds = 0;
    /// 0 — победа A, 1 — победа B, 2 — обе стороны выстояли.
    uint8_t outcome = 2;
};

/// Максимум раундов. Бой обязан завершаться: если за это время никто никого
/// не добил, стороны расходятся. Иначе два флота с сильной обороной могли бы
/// молотить друг друга бесконечно, вешая тик.
inline constexpr uint32_t kMaxBattleRounds = 14;

/// Разрешить сражение.
///
/// Чистая функция: те же входные данные дают тот же исход. Отсюда бесплатно
/// получаются реплеи и разбор боя покадрово.
BattleResult resolveBattle(const BattleSide& a, const BattleSide& b, Rng& rng);

/// Очки боевой силы: грубая оценка «кто сильнее» без прогона сражения.
/// Нужна интерфейсу и ботам, но НЕ решает исход — его решает контр-система.
uint32_t battleStrength(const Fleet& fleet, const FleetArmament& armament);

/// Суммарная боевая прочность флота.
int64_t fleetHitPoints(const Fleet& fleet);

/// Что осталось от флота, сохранившего долю `fraction` своей прочности.
///
/// Потери — это ровно выбитая прочность, потраченная на корабли, начиная
/// с самых дешёвых: эскорт для того во флоте и стоит. Публична, потому что
/// это отдельная модель со своими свойствами, и проверять их надо напрямую,
/// а не сквозь прогон боя.
Fleet survivors(const Fleet& fleet, fx fraction);

}  // namespace pw::sim
