// pw_sim — галактика: звёздные системы, планеты и граф гиперлиний.
//
// ТОПОЛОГИЯ — ГРАФ, А НЕ СВОБОДНЫЙ КОСМОС (ADR-006). Флот ходит только по
// рёбрам. Из этого следуют горлышки, оборонительные рубежи и позиционная
// игра; свободное перемещение превратило бы стратегию в гонку скоростей.
// Заодно разрезы графа с малым числом рёбер дают естественные границы
// серверных регионов — решение геймдизайна прямо удешевляет инфраструктуру.
//
// Граф хранится в сжатых строках (CSR): один массив соседей и массив
// смещений. Топология внутри сезона почти не меняется, поэтому такая
// раскладка выигрывает у списков указателей и по памяти, и по обходу.
#pragma once

#include <cstdint>
#include <vector>

#include "pw/core/fixed.h"
#include "pw/sim/world.h"

namespace pw::sim {

// ---------------------------------------------------------------------------
// Компоненты
//
// У всех явное дополнение до границы выравнивания. Это не педантизм:
// has_unique_object_representations отвергает типы с байтами выравнивания,
// потому что их содержимое не определено и хеш мира начал бы плясать.
// ---------------------------------------------------------------------------

enum class StarClass : uint8_t {
    Red = 0,      // тусклая, бедная система
    Yellow,       // обычная
    Blue,         // богатая энергией
    Neutron,      // редкие ресурсы, опасна
    BlackHole,    // особая, ценнейшая
    Count
};

enum class PlanetClass : uint8_t {
    Barren = 0,   // мало слотов, зато часто с редкими ресурсами
    Desert,
    Ocean,
    Volcanic,
    GasGiant,     // много слотов под добычу газа
    AsteroidBelt, // минералы
    Count
};

/// Звёздная система: узел графа.
struct StarSystem {
    fx x, y;              // положение на карте галактики
    uint32_t seed;        // сид содержимого — от него зависят планеты
    /// Свой номер в графе. Нужен обработчикам, которым иначе пришлось бы
    /// ходить в Galaxy за обратным отображением «сущность -> индекс».
    uint32_t index;
    uint8_t starClass;    // StarClass
    uint8_t planetCount;
    uint8_t ring;         // 0 — ядро, дальше кольца, последнее — фронтир
    uint8_t reserved;
    uint32_t reserved2;   // явное дополнение до 32 байт
};
static_assert(sizeof(StarSystem) == 32, "структура обязана быть без дыр");

/// Планета. Экономика на слотах и специализации (ADR-004).
struct Planet {
    uint32_t system;         // индекс родительской системы
    uint8_t planetClass;     // PlanetClass
    uint8_t slots;           // сколько зданий помещается
    uint8_t specialization;  // выбирается игроком, 0 — не задана
    uint8_t orbit;           // порядковый номер от звезды
};
static_assert(sizeof(Planet) == 8, "структура обязана быть без дыр");

/// Империя: ресурсы и столица.
struct Empire {
    fx energy, minerals, alloys, research, influence;
    uint32_t id;
    uint32_t capitalSystem;
};
static_assert(sizeof(Empire) == 48, "структура обязана быть без дыр");

/// Кому принадлежит сущность. Отдельным компонентом, а не полем:
/// владение навешивается и снимается, а положение и класс — нет.
struct Owner {
    uint32_t empire;
    uint32_t reserved;
};
static_assert(sizeof(Owner) == 8, "структура обязана быть без дыр");

// ---------------------------------------------------------------------------
// Генератор
// ---------------------------------------------------------------------------

struct GalaxyParams {
    uint64_t seed = 0x50414E45'54574152ull;  // "PLANETWAR"
    uint32_t systemCount = 500;
    /// Радиус диска галактики в игровых единицах.
    fx radius = fx::fromInt(1200);
    /// Сколько спиральных рукавов. Рукава дают неравномерную плотность,
    /// а из неё — естественные узкие места на карте.
    uint32_t arms = 4;
    /// Минимальное расстояние между системами: без него звёзды слипаются
    /// в комки и карта становится нечитаемой.
    fx minSpacing = fx::fromInt(28);
    /// Предельная длина гиперлинии. Ограничение и есть то, что превращает
    /// облако точек в граф с горлышками.
    fx maxLaneLength = fx::fromInt(150);
    /// К скольким ближайшим соседям тянуть линии.
    uint32_t lanesPerSystem = 3;

    // --- форма спирали ---
    //
    // Это параметры БАЛАНСА, а не константы движка. Форма галактики задаёт
    // темп войны и то, где возникают горлышки, поэтому на Фазе 3 они уедут
    // в таблицу баланса и будут крутиться в редакторе (ADR-010). Пока лежат
    // здесь с осмысленными значениями по умолчанию.

    /// Доля систем внутри рукавов, остальные — межрукавное поле.
    ///
    /// Доминирующий рычаг формы карты. Замер на 500 системах:
    ///   70% -> диаметр 34 прыжка, средняя степень 3.71
    ///   80% -> диаметр 49 прыжков, средняя степень 3.56
    ///   90% -> диаметр 50 прыжков, средняя степень 3.64
    /// Чем плотнее системы жмутся к рукавам, тем длиннее пути: межрукавное
    /// поле работает мостами между соседними рукавами.
    ///
    /// 72% выбрано замером, а не на глаз: оно даёт и короткие пути,
    /// и низкую степень. Низкая степень важна отдельно — из неё берутся
    /// горлышки, а без них нет позиционной игры (ADR-006).
    uint32_t armFractionPercent = 72;
    /// Разброс поперёк рукава, в долях оборота. На диаметр влияет слабо
    /// (39 против 42 прыжков при изменении вдвое) — это чисто визуальный
    /// параметр: чем больше, тем мягче спираль.
    fx armSpread = fx::fromFraction(1, 10);
    /// Разброс по радиусу. Без него рукав вырождается в нитку в один ряд
    /// систем, и граф становится одномерным.
    fx radialJitter = fx::fromFraction(1, 9);
    /// На сколько оборотов закручена спираль от центра к краю.
    fx twist = fx::fromFraction(1, 2);

    // --- проход «срезок» ---
    //
    // Лечит характерную болезнь генерации по ближайшим соседям: две системы
    // физически рядом, а по графу между ними двадцать прыжков, потому что
    // расстояние чуть превысило предел гиперлинии. Из таких мест и берётся
    // огромный разброс диаметра карты между сидами.
    //
    // Срезка добавляется ровно там, где геометрия её и так подсказывает,
    // поэтому горлышки не разрушаются — карта просто перестаёт быть
    // случайно вытянутой.

    /// Предельная длина срезки, в процентах от обычной гиперлинии.
    uint32_t shortcutRangePercent = 190;
    /// Начиная со скольких прыжков физически близкие системы считаются
    /// неоправданно далёкими.
    uint32_t shortcutHopThreshold = 7;
    /// Сколько проходов делать. Каждый пересчитывает расстояния заново.
    uint32_t shortcutRounds = 3;
};

/// Галактика: сущности систем и граф связей между ними.
///
/// Компоненты живут в World, топология — здесь. Разделение намеренное:
/// граф внутри сезона статичен, и держать его в ECS значило бы платить
/// за гибкость, которая не нужна.
class Galaxy {
public:
    /// Построить галактику. Мир должен быть пуст, компоненты —
    /// зарегистрированы (см. registerGalaxyComponents).
    void generate(World& world, const GalaxyParams& params);

    uint32_t systemCount() const { return uint32_t(systems_.size()); }
    Entity systemEntity(uint32_t index) const { return systems_[index]; }

    /// Соседи системы по гиперлиниям.
    const uint32_t* neighbors(uint32_t index) const {
        return adjacency_.data() + offsets_[index];
    }
    uint32_t neighborCount(uint32_t index) const {
        return offsets_[index + 1] - offsets_[index];
    }

    /// Всего гиперлиний. Каждая учитывается один раз, а не дважды.
    uint32_t laneCount() const { return laneCount_; }

    /// Связен ли граф. Несвязная галактика — это отрезанные игроки,
    /// до которых нельзя ни долететь, ни довоевать.
    bool connected() const;

    /// Кратчайший путь в прыжках. Возвращает число прыжков либо -1.
    int32_t hopDistance(uint32_t from, uint32_t to) const;

    /// Длина гиперлинии между соседними системами. Для несоседних — 0.
    fx laneLength(uint32_t a, uint32_t b) const;

    /// Кратчайший по РАССТОЯНИЮ путь, алгоритм A*.
    ///
    /// Именно по расстоянию, а не по числу прыжков: флот тратит время на
    /// пролёт линии, и три коротких прыжка бывают быстрее одного длинного.
    /// out заполняется последовательностью систем, включая начальную
    /// и конечную. Возвращает число прыжков либо -1, если пути нет.
    int32_t findPath(uint32_t from, uint32_t to, std::vector<uint32_t>& out) const;

    /// Первый шаг пути. Флот пересчитывает его в момент прибытия в узел,
    /// а не хранит весь маршрут: так приказ переживает изменения карты,
    /// а компонент остаётся фиксированного размера.
    int32_t nextHop(uint32_t from, uint32_t to) const;

    /// Расстояние по прямой. Нужно и оценке A*, и логистическим штрафам.
    fx straightDistance(uint32_t a, uint32_t b) const;

    uint64_t hash() const;

private:
    void placeSystems(const GalaxyParams& params);
    void linkSystems(const GalaxyParams& params);
    void spawnPlanets(World& world, const GalaxyParams& params);

    struct Point {
        fx x, y;
        uint8_t ring;
    };

    std::vector<Point> points_;
    std::vector<Entity> systems_;
    std::vector<uint32_t> offsets_;    // размер systemCount + 1
    std::vector<uint32_t> adjacency_;
    uint32_t laneCount_ = 0;
};

/// Зарегистрировать компоненты галактики.
///
/// Порядок вызовов задаёт идентификаторы, а те входят в хеш мира. Поэтому
/// регистрация собрана в одной функции: изменить порядок здесь — значит
/// изменить хеш всей вселенной.
void registerGalaxyComponents(World& world);

}  // namespace pw::sim
