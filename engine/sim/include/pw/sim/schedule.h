// pw_sim — тик и расписание систем.
//
// Система — это функция, обрабатывающая мир за один тик. Расписание хранит
// их в порядке добавления и выполняет строго в нём.
//
// Порядок явный и неизменный, потому что от него зависит результат. Если бы
// системы запускались в порядке хеш-таблицы или по мере готовности, мир
// начал бы зависеть от раскладки памяти и от планировщика потоков — то есть
// перестал бы воспроизводиться.
//
// Параллелизм появляется ВНУТРИ системы (обход разбивается на куски через
// job system из pw_core), а не между системами. Тогда порядок применения
// результатов остаётся под нашим контролем.
#pragma once

#include <cstdint>
#include <vector>

#include "pw/core/fixed.h"
#include "pw/sim/world.h"

namespace pw::sim {

/// Частота тика горячих систем: тех, где есть онлайн-игроки, бой или осада.
/// Тёплые тикают раз в секунду, холодные не тикают вовсе и досчитываются
/// при чтении — см. docs/03-NETWORK-AND-SERVER.md.
inline constexpr int64_t kTicksPerSecond = 10;

// ---------------------------------------------------------------------------
// ЧАСЫ ИГРЫ. Единица действия — ЧАС, а не минута.
//
// Это главное число всего баланса, и оно не записано ни в одной константе:
// оно записано во всех сразу. Здесь оно объяснено один раз, чтобы каждый,
// кто правит скорость осады или выработку шахты, знал, из чего она взялась.
//
// ИГРОВАЯ СЕКУНДА РАВНА РЕАЛЬНОЙ. Сервер тикает по своим часам, и никакого
// «игрового календаря», бегущего быстрее настоящего, в проекте нет. Значит
// длительность любого действия — это буквально время, которое ждёт человек.
//
// ИЗ ЧЕГО ВЫВЕДЕН МАСШТАБ. Сезон длится одиннадцать недель, а человек живёт
// сутками: заходит один-три раза в день на полчаса-час. Отсюда три
// требования, и все три про часы, а не про минуты:
//
//   1. Ничего важного не должно решиться, пока игрок спит. Скромная осада —
//      четырнадцать часов, самый мощный штурм — почти пять. Проснуться
//      и обнаружить, что империи больше нет, невозможно по конструкции.
//   2. Между двумя заходами должно что-то ЗАВЕРШИТЬСЯ, иначе игра выглядит
//      застывшей. Шахта встаёт за двадцать пять минут, перелёт по линии —
//      минут пятнадцать: и то и другое умещается в один сеанс.
//   3. Крупное решение обязано стоить суток. Титан строится трое суток,
//      переброска флота через галактику — половину дня. Такое планируют
//      заранее, а планирование и есть стратегия.
//
// ОТКУДА ВЗЯЛОСЬ ЧИСЛО 12.5. Первая версия игры была рассчитана на сезон
// в два часа: столько удобно прогонять в CI. Все её числа — скорость осады,
// выработка зданий, скорости корпусов, время стройки — оказались подогнаны
// под «единица действия равна минуте». Требования выше дают единицу в час,
// то есть ровно в 12.5 раз крупнее (шестьдесят семь минут скромной осады
// превращаются в четырнадцать часов). Один и тот же множитель применён
// ко ВСЕМ длительностям и ко всем скоростям — поэтому весь ранее проверенный
// баланс уцелел: игра не изменилась, она замедлилась.
//
// Исключения из множителя есть, их два, и оба объяснены на месте:
// период волны кризиса (kCrisisWaveSeconds) и шаг начисления престижа
// (kPrestigeIntervalSeconds) выведены из ДЛИНЫ СТАДИИ, а не из масштаба
// действий.
//
// Проверять сезон целиком на обычном шаге нельзя — это сорок восемь
// миллионов тиков. Для этого есть сжатие времени, см. SimTempo ниже.
// ---------------------------------------------------------------------------

/// Во сколько раз шаг симуляции ГРУБЕЕ обычного.
///
/// ЗАЧЕМ ОН НУЖЕН. Живой сезон длится одиннадцать недель, а осада — часы.
/// Прогнать такой сезон целиком значит отсчитать почти пятьдесят миллионов
/// тиков: двадцать минут машинного времени на каждую проверку. Проверка,
/// которую запускают раз в день, перестаёт ловить ошибки в тот же час,
/// когда их сделали.
///
/// Сжатие решает это одним числом: при `tempo = 500` один тик проживает
/// пятьдесят игровых секунд, и весь сезон укладывается в сотню тысяч тиков,
/// то есть в пару секунд. Все длительности сжимаются ВМЕСТЕ, потому что
/// все они выражены в игровых секундах, а не в тиках.
///
/// ЧТО СЖАТЫЙ ПРОГОН ПРОВЕРЯЕТ. Пропорции, а не точность: при шаге
/// в пятьдесят секунд флот проскакивает короткие линии за один тик,
/// а бой и осада идут крупными кусками. Этого хватает, чтобы поймать
/// «империя не выросла», «кризис не пришёл», «тоннаж взялся из ниоткуда» —
/// то есть всё, ради чего прогон и существует. Точность проверяют
/// юнит-тесты на обычном шаге.
///
/// НЕ ПУТАТЬ СО СКОРОСТЬЮ СЕРВЕРА. Скорость сервера заставляет тикать чаще
/// в РЕАЛЬНОМ времени и не трогает игровых длительностей: сезон при ней
/// остаётся одиннадцатинедельным, просто проходит быстрее по часам.
/// Сжатие меняет сами длительности и потому годится только для проверок.
struct SimTempo {
    int64_t scale = 1;
};

/// Сколько игровых секунд прошло к этому тику.
inline int64_t gameSecondsAt(uint64_t tick, int64_t tempo) {
    return int64_t(tick) * (tempo > 0 ? tempo : 1) / kTicksPerSecond;
}

/// Сколько тиков занимают столько-то игровых секунд. Не меньше одного:
/// событие, на которое отвели ноль тиков, происходило бы каждый тик.
inline int64_t ticksForSeconds(int64_t seconds, int64_t tempo) {
    const int64_t ticks = seconds * kTicksPerSecond / (tempo > 0 ? tempo : 1);
    return ticks > 0 ? ticks : 1;
}

/// Что система знает о текущем тике.
///
/// Шаг времени — фиксированная точная дробь, а не измеренное время кадра.
/// Переменный шаг сделал бы результат зависящим от нагрузки на машину,
/// и два клиента посчитали бы разное.
struct TickContext {
    uint64_t tick = 0;
    /// Сжатие времени. Единица — обычный шаг в одну десятую секунды.
    int64_t tempo = 1;
    fx delta = fx::fromFraction(1, kTicksPerSecond);

    /// Собрать контекст тика с заданным сжатием. Через фабрику, а не
    /// скобками: шаг и сжатие обязаны быть согласованы, а два независимых
    /// поля однажды разъедутся.
    static TickContext at(uint64_t tick, int64_t tempo = 1) {
        const int64_t scale = tempo > 0 ? tempo : 1;
        return TickContext{tick, scale, fx::fromFraction(scale, kTicksPerSecond)};
    }

    /// Игровое время от начала сезона, в секундах.
    fx elapsed() const {
        return fx::fromFraction(int64_t(tick) * tempo, kTicksPerSecond);
    }
    int64_t gameSeconds() const { return gameSecondsAt(tick, tempo); }
    int64_t ticksFor(int64_t seconds) const { return ticksForSeconds(seconds, tempo); }
};

class Schedule {
public:
    using SystemFn = void (*)(World&, const TickContext&);

    /// Имя нужно для профилирования и для сообщений об ошибках: когда мир
    /// разъезжается, первым делом хочется знать, на какой системе.
    void add(const char* name, SystemFn function);

    void run(World& world, const TickContext& context) const;

    size_t systemCount() const { return systems_.size(); }
    const char* systemName(size_t index) const { return systems_[index].name; }

private:
    struct Entry {
        const char* name;
        SystemFn function;
    };
    std::vector<Entry> systems_;
};

/// Мир, расписание и счётчик тиков вместе.
///
/// Это и есть то, что компилируется в headless-сервер без единой строки
/// рендера, и то же самое исполняет клиент. Один код правил на обоих концах —
/// расхождение баланса между ними технически невозможно.
class Simulation {
public:
    World& world() { return world_; }
    const World& world() const { return world_; }
    Schedule& schedule() { return schedule_; }

    uint64_t tick() const { return tick_; }

    /// Сжатие времени. Единица — обычный шаг. См. SimTempo выше.
    void setTempo(int64_t scale) { tempo_ = scale > 0 ? scale : 1; }
    int64_t tempo() const { return tempo_; }
    /// Игровое время от начала, в секундах.
    int64_t gameSeconds() const { return gameSecondsAt(tick_, tempo_); }

    /// Один тик.
    void step();
    /// Несколько тиков подряд.
    void advance(uint64_t ticks);

    /// Хеш состояния: мир плюс номер тика.
    uint64_t hash() const;

private:
    World world_;
    Schedule schedule_;
    uint64_t tick_ = 0;
    int64_t tempo_ = 1;
};

}  // namespace pw::sim
