// pw_sim — постройка кораблей.
//
// Флот собирается в системе, у которой есть верфи, и оплачивается сплавами
// из общей казны империи. Верфь решает не «сколько построю всего», а «как
// быстро смогу потратить»: она ограничивает темп сборки, а не объём.
//
// Готовый корабль появляется НЕ сразу, а через буфер отложенных команд:
// создавать сущности внутри обхода нельзя, иначе строки поедут прямо под
// ногами (см. commands.h).
#pragma once

#include <cstdint>

#include "pw/core/fixed.h"
#include "pw/sim/economy.h"
#include "pw/sim/fleet.h"
#include "pw/sim/schedule.h"
#include "pw/sim/world.h"

namespace pw::sim {

/// Очередь постройки в системе. Висит на сущности системы.
///
/// Одна очередь на систему, а не на верфь: верфи складывают темп, но заказ
/// общий. Иначе игроку пришлось бы раскладывать заказы по зданиям — ровно
/// тот микроменеджмент, которого мы избегаем.
struct BuildQueue {
    uint8_t hull;        // Hull; None означает, что ничего не строится
    uint8_t reserved0;
    uint8_t reserved1;
    uint8_t reserved2;
    uint32_t remaining;  // сколько кораблей осталось построить
    fx invested;         // сплавов вложено в текущий корабль
};
static_assert(sizeof(BuildQueue) == 16, "структура обязана быть без дыр");

/// Стройка на планете. Висит на сущности планеты.
///
/// ЗДАНИЕ НЕ ПОЯВЛЯЕТСЯ ПО ЩЕЛЧКУ. Оно строится минуты, и всё это время
/// стройка видна: владельцу — в панели планеты, соседу — по разведке.
///
/// Мгновенная застройка ломала две вещи сразу. Накопленный запас минералов
/// превращался в готовую империю одним нажатием, и осада теряла смысл:
/// осаждённый достраивал крепость ровно в тот тик, когда оборона падала.
/// Со временем постройки решение «что строить» становится ставкой на
/// будущее, а не реакцией на настоящее.
///
/// Одна стройка на планету, а не очередь: очередь — это микроменеджмент,
/// от которого игра уходит осознанно (ADR-004). Хочешь строить быстрее —
/// строй на разных планетах.
/// Одна стройка идёт, остальные ждут очереди.
///
/// Очередь короткая и намеренно: она нужна, чтобы игрок мог наметить план
/// застройки одним заходом и уйти, а не чтобы расписывать планету на час
/// вперёд. Без очереди второй щелчок отменял бы первый — поведение, которое
/// человек читает как «игра съела мой приказ».
struct PlanetConstruction {
    /// Значение поля slot, означающее «ничего не строится».
    static constexpr uint8_t kNoSlot = 0xFF;
    /// Сколько заказов помещается в очередь сверх текущего.
    static constexpr uint8_t kQueueLimit = 4;

    uint8_t slot;        // слот текущей стройки, kNoSlot — стройки нет
    uint8_t building;    // Building, который возводится
    uint8_t queued;      // сколько заказов ждёт очереди
    /// Оплачена ли текущая стройка. Ноль — заказ принят, но минералов
    /// на него ещё не хватило, и время не идёт.
    uint8_t paid;
    uint8_t queueSlots[kQueueLimit];
    uint8_t queueBuildings[kQueueLimit];
    uint32_t elapsed;    // тиков с момента оплаты
};
static_assert(sizeof(PlanetConstruction) == 16, "структура обязана быть без дыр");

/// Поставить заказ. Заменяет текущий: вложенные сплавы в текущий корабль
/// при смене типа теряются — за перестройку планов надо платить.
void enqueueBuild(BuildQueue& queue, Hull hull, uint32_t count);

/// Пустая стройка: ничего не строится, очередь пуста.
PlanetConstruction emptyConstruction();

/// Поставить стройку в слот. Если планета уже строит — встать в очередь.
///
/// Building::None означает ОТМЕНУ этого слота: текущая стройка бросается
/// (оплаченные минералы теряются — за перестройку планов надо платить),
/// ожидающая просто вычёркивается. Снос уже построенного здания к очереди
/// отношения не имеет и делается мгновенно.
///
/// false — очередь полна и заказ не принят. Молчаливый отказ был бы худшим
/// исходом: человек жмёт клавишу, ничего не происходит, и понять почему
/// неоткуда.
bool enqueueConstruction(PlanetConstruction& site, uint8_t slot, Building building);

/// Доля готовности текущей стройки в сотых. 0, если ничего не строится
/// или стройка ещё не оплачена.
///
/// Считается здесь, а не на клиенте: клиент не знает ни цен, ни сроков,
/// и знать их ему незачем — он показывает то, что прислал сервер.
uint32_t constructionPercent(const PlanetConstruction& site);

/// Сколько тиков строится здание. Выводится из цены, а не задаётся
/// отдельно: два независимых числа однажды разошлись бы, и появилось бы
/// дешёвое здание, которое строится дольше дорогого.
int64_t buildingTicks(Building building);

/// Списать сплавы и собрать готовые корабли.
///
/// Идёт ПОСЛЕ экономики (доход уже начислен) и ДО применения команд.
void systemProduction(World& world, const TickContext& context);

/// Вести стройки на планетах: списывать минералы и достраивать здания.
///
/// Идёт ПОСЛЕ экономики (доход уже начислен) и ДО применения команд.
void planetConstructionTick(World& world, const TickContext& context);

/// Распустить пустые флоты.
///
/// Флот без кораблей продолжал бы занимать место, обходиться каждый тик
/// и, что хуже, считаться присутствием в системе. Показательный случай
/// использования буфера команд: удаление сущности из обхода.
void systemDisbandEmpty(World& world, const TickContext& context);

void registerProductionComponents(World& world);

/// Навесить очередь постройки на все системы галактики, а стройку — на все
/// планеты.
void initialiseProduction(World& world, const class Galaxy& galaxy);

}  // namespace pw::sim
