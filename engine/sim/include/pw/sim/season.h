/// Пересчитать стадию сезона. Идёт ПЕРВОЙ в тике: всё остальное на неё
/// смотрит, и все обязаны видеть одну и ту же.
void systemSeason(World& world, const TickContext& context);

/// Выпустить очередную волну кризиса, если пора.
void systemCrisis(World& world, const TickContext& context);

/// Начислить престиж за этот тик.
void systemPrestige(World& world, const TickContext& context);

void registerSeasonComponents(World& world);

