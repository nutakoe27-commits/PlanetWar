// pw_sim — владение планетами, захват и осада.
//
// ВЛАДЕНИЕ ЛЕЖИТ НА ПЛАНЕТАХ, а не на системах.
//
// Это то, ради чего игра и затевалась: «захват множества планет вплоть до
// бесконечности». Система с четырьмя планетами перестаёт быть одним щелчком
// — её можно взять наполовину, удержать одну планету в чужом тылу, годами
// делить с соседом. Владение системой остаётся, но становится ПРОИЗВОДНЫМ:
// система принадлежит тому, у кого в ней больше планет. Оно нужно карте,
// поиску пути и обороне, но решают планеты.
//
// ГЛАВНОЕ ПРАВИЛО ЭТОГО МОДУЛЯ: мгновенных потерь в игре нет.
//
// Захват чужой планеты требует непрерывной осады в ЧАСЫ. За это время
// владелец успевает получить уведомление, союзники — увидеть осаду
// на карте альянса и прийти, а осаждающий флот всё это время сам стоит
// на месте и уязвим.
//
// Именно эта механика делает часовой пояс игрока менее решающим, не запрещая
// при этом играть в определённое время суток. Проснуться и обнаружить, что
// империи больше нет, здесь невозможно по конструкции — и это не пожелание,
// а арифметика: скромная осада длиннее ночного сна.
#pragma once

#include <cstdint>
#include <vector>

#include "pw/core/fixed.h"
#include "pw/sim/schedule.h"
#include "pw/sim/world.h"

namespace pw::sim {

class Galaxy;

/// «Ничья» планета или система.
inline constexpr uint32_t kNoEmpire = 0xFFFFFFFFu;

// ---------------------------------------------------------------------------
// Числа осады
//
// Игровая секунда равна реальной, поэтому это буквально то время, которое
// ждёт игрок. Числа выведены из требования дизайна «осада переживает ночь»,
// а не подобраны на глаз. Общий масштаб — в pw/sim/schedule.h, «ЧАСЫ ИГРЫ».
// ---------------------------------------------------------------------------

/// Потолок готовности обороны.
inline const fx kReadinessMax = fx::fromInt(100);

/// Базовая скорость падения готовности под осадой, единиц в секунду.
///
/// 100 / (1/500) = 50 000 секунд, то есть ЧЕТЫРНАДЦАТЬ ЧАСОВ для скромного
/// флота. Собранный по уму штурм (полный тоннажный потолок плюс четыре
/// монитора) втрое быстрее — четыре часа сорок минут. Планета под щитами
/// держится вчетверо дольше того и другого.
///
/// Нижняя граница здесь — не вкусовая: четыре с половиной часа длиннее
/// любого сна и любого рабочего дня. Ни одна планета в игре не может быть
/// потеряна незамеченной, и это проверяется тестом, а не обещанием.
inline const fx kSiegeBaseRate = fx::fromFraction(1, 500);

/// Тоннаж, при котором скорость осады удваивается. Больше флот — быстрее
/// осада, но с затуханием: втрое больший флот не берёт систему втрое быстрее.
/// Иначе выигрывал бы просто тот, кто собрал всё в один кулак.
inline constexpr uint32_t kSiegeTonnageScale = 200;

/// Осадная мощь, дающая такую же прибавку, как полный тоннажный потолок.
///
/// Шестьдесят четыре — это четыре монитора. То есть специально собранный
/// осадный отряд из четырёх кораблей ломает оборону примерно так же
/// быстро, как двести тонн линейного флота, а вместе они — вдвое быстрее
/// любого из них. Отсюда и смысл готовить осаду отдельно: линкоры
/// выигрывают сражение за систему, мониторы забирают планету.
inline constexpr uint32_t kSiegeMonitorScale = 64;

/// Восстановление готовности в мирное время, единиц в секунду.
///
/// Полное восстановление с нуля — около двадцати одного часа: планета,
/// пережившая осаду, остаётся уязвимой почти сутки, и вернуться за ней
/// на следующий день — законный ход. Гарнизон сокращает этот срок втрое
/// (см. kGarrisonRegenBonus), и в этом весь его смысл.
inline const fx kReadinessRegen = fx::fromFraction(1, 750);

/// С какой долей готовности достаётся только что взятая система.
/// Свежий захват слаб — отбить его обратно реально, и фронт может ходить.
inline const fx kCaptureReadinessShare = fx::fromFraction(1, 4);

// ---------------------------------------------------------------------------
// Компоненты
// ---------------------------------------------------------------------------

/// Оборона планеты. Висит на сущности планеты.
struct PlanetDefense {
    fx readiness;
    fx maxReadiness;
};
static_assert(sizeof(PlanetDefense) == 16, "структура обязана быть без дыр");

/// Текущая осада или занятие планеты.
struct SiegeState {
    uint32_t besieger;   // kNoEmpire, если ничего не происходит
    uint32_t ticks;      // сколько тиков подряд идёт — для уведомлений игроку
};
static_assert(sizeof(SiegeState) == 8, "структура обязана быть без дыр");

// ---------------------------------------------------------------------------
// Присутствие флотов
// ---------------------------------------------------------------------------

/// Кто где стоит. Пересобирается каждый тик перед осадой.
///
/// Хранится список присутствующих империй с их тоннажем, а не «свои против
/// чужих»: владение теперь на планетах, и в одной системе у соседних
/// орбит могут быть разные хозяева. Кто кому враг — вопрос, у которого
/// нет ответа на уровне системы, только на уровне планеты.
class Presence {
public:
    struct Entry {
        /// Предел числа империй, флоты которых различаются в одной системе.
        ///
        /// Восемь — это потолок мест в сезоне на Фазе 1. Когда сезон
        /// вырастет до сотен игроков, различать их поимённо в каждой
        /// системе станет и невозможно, и бессмысленно: там единицей
        /// станет альянс, и сюда придёт его номер вместо номера империи.
        static constexpr uint32_t kMaxPresent = 8;

        uint32_t empires[kMaxPresent] = {};
        uint32_t tonnages[kMaxPresent] = {};
        /// Осадная мощь: мониторы и титаны против тоннажа вообще.
        ///
        /// Отдельным числом, потому что это ДРУГАЯ работа. Сто корветов
        /// выигрывают сражение и почти не двигают осаду; три монитора
        /// проигрывают любому бою и ломают оборону вдвое быстрее. Без
        /// разделения этих двух чисел осадный корабль был бы просто
        /// плохим кораблём линии.
        uint32_t sieges[kMaxPresent] = {};
        uint32_t count = 0;

        void add(uint32_t empire, uint32_t tonnage, uint32_t siege = 0);

        /// Сколько тоннажа привела эта империя. Ноль — её здесь нет.
        uint32_t tonnageOf(uint32_t empire) const;

        /// Осадная мощь этой империи здесь.
        uint32_t siegeOf(uint32_t empire) const;

        /// Сильнейший из ЧУЖИХ для владельца `owner`.
        /// kNoEmpire, если чужих нет.
        uint32_t strongestOther(uint32_t owner, uint32_t& tonnage) const;

        /// Сколько РАЗНЫХ чужих империй присутствует.
        ///
        /// Различие с числом флотов принципиальное: правило «ничью планету
        /// занимает только единственный претендент» должно считать
        /// претендентов. Пока считались флоты, империя, приведшая два
        /// отряда, блокировала занятие сама себе — и экспансия вставала
        /// намертво. Поймал прогон сезона: боты расселялись по три системы
        /// за шесть часов вместо полусотни.
        uint32_t othersCount(uint32_t owner) const;
    };

    void rebuild(World& world, uint32_t systemCount);

    void resize(uint32_t systemCount) { entries_.assign(systemCount, Entry{}); }

    const Entry& at(uint32_t system) const { return entries_[system]; }
    uint32_t size() const { return uint32_t(entries_.size()); }

private:
    std::vector<Entry> entries_;
};

// ---------------------------------------------------------------------------
// Системы тика
// ---------------------------------------------------------------------------

/// Пересчитать владельцев систем по владельцам планет.
///
/// Система принадлежит тому, у кого в ней больше планет; при равенстве —
/// никому. Идёт ПЕРВОЙ в тике: и присутствие, и бой, и поиск цели ботом
/// смотрят на владельца системы, и все они обязаны видеть одно и то же.
void systemControlRollup(World& world, const TickContext& context);

/// Пересобрать карту присутствия. Должна идти ДО осады.
void systemPresence(World& world, const TickContext& context);

/// Осада, занятие ничьих планет и восстановление обороны.
///
/// Флот работает по ОДНОЙ планете за раз, в порядке орбит. Иначе система
/// с четырьмя планетами бралась бы так же быстро, как с одной, и число
/// планет перестало бы что-либо значить — а это главная валюта игры.
void systemSiege(World& world, const TickContext& context);

/// Зарегистрировать компоненты владения. После галактики и флотов.
void registerControlComponents(World& world);

/// Навесить владение, оборону и состояние осады на все ПЛАНЕТЫ, а на
/// системы — производного владельца.
///
/// Компоненты навешиваются СРАЗУ ВСЕМ, включая ничьи. Смена владельца тогда
/// становится записью в поле, а не добавлением компонента: сущность не
/// переезжает между таблицами, и захват можно обрабатывать прямо в обходе.
void initialiseControl(World& world, const Galaxy& galaxy);

}  // namespace pw::sim
