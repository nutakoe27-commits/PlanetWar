// pw_sim — владение системами, захват и осада.
//
// ГЛАВНОЕ ПРАВИЛО ЭТОГО МОДУЛЯ: мгновенных потерь в игре нет.
//
// Захват чужой системы требует непрерывной осады в десятки минут. За это
// время владелец успевает получить уведомление, союзники — увидеть осаду
// на карте альянса и прийти, а осаждающий флот всё это время сам стоит
// на месте и уязвим.
//
// Именно эта механика делает часовой пояс игрока менее решающим, не запрещая
// при этом играть в определённое время суток. Проснуться и обнаружить, что
// империи больше нет, здесь невозможно по конструкции.
#pragma once

#include <cstdint>
#include <vector>

#include "pw/core/fixed.h"
#include "pw/sim/schedule.h"
#include "pw/sim/world.h"

namespace pw::sim {

class Galaxy;

/// «Ничья» система.
inline constexpr uint32_t kNoEmpire = 0xFFFFFFFFu;

// ---------------------------------------------------------------------------
// Числа осады
//
// Игровая секунда равна реальной, поэтому это буквально то время, которое
// ждёт игрок. Числа выведены из требования дизайна «осада 30–90 минут»,
// а не подобраны на глаз.
// ---------------------------------------------------------------------------

/// Потолок готовности обороны.
inline const fx kReadinessMax = fx::fromInt(100);

/// Базовая скорость падения готовности под осадой, единиц в секунду.
/// 100 / (1/40) = 4000 секунд, то есть 67 минут для скромного флота.
inline const fx kSiegeBaseRate = fx::fromFraction(1, 40);

/// Тоннаж, при котором скорость осады удваивается. Больше флот — быстрее
/// осада, но с затуханием: втрое больший флот не берёт систему втрое быстрее.
/// Иначе выигрывал бы просто тот, кто собрал всё в один кулак.
inline constexpr uint32_t kSiegeTonnageScale = 200;

/// Восстановление готовности в мирное время, единиц в секунду.
/// Полное восстановление с нуля — около 100 минут: система, пережившая
/// осаду, ещё долго остаётся уязвимой.
inline const fx kReadinessRegen = fx::fromFraction(1, 60);

/// Сколько секунд флот занимает ничью систему. Пять минут: экспансия
/// в пустоту не должна быть мучением, воюют не за неё.
inline constexpr int64_t kClaimSeconds = 300;

/// С какой долей готовности достаётся только что взятая система.
/// Свежий захват слаб — отбить его обратно реально, и фронт может ходить.
inline const fx kCaptureReadinessShare = fx::fromFraction(1, 4);

// ---------------------------------------------------------------------------
// Компоненты
// ---------------------------------------------------------------------------

/// Оборона системы. Висит на сущности системы.
struct SystemDefense {
    fx readiness;
    fx maxReadiness;
};
static_assert(sizeof(SystemDefense) == 16, "структура обязана быть без дыр");

/// Текущая осада или занятие системы.
struct SiegeState {
    uint32_t besieger;   // kNoEmpire, если ничего не происходит
    uint32_t ticks;      // сколько тиков подряд идёт — для уведомлений игроку
};
static_assert(sizeof(SiegeState) == 8, "структура обязана быть без дыр");

// ---------------------------------------------------------------------------
// Присутствие флотов
// ---------------------------------------------------------------------------

/// Кто где стоит. Пересобирается каждый тик перед осадой.
///
/// Хранится не полный список империй по системам, а только то, что нужно
/// для решения: тоннаж владельца и сильнейший враждебный тоннаж. Полный
/// список рос бы как число систем на число империй и не пережил бы
/// безграничную галактику Фазы 4.
class Presence {
public:
    struct Entry {
        uint32_t ownerTonnage = 0;      // силы нынешнего владельца
        uint32_t hostileEmpire = kNoEmpire;
        uint32_t hostileTonnage = 0;    // сильнейший из чужих
        uint32_t hostileCount = 0;      // сколько разных чужих империй
    };

    void rebuild(World& world, uint32_t systemCount);

    /// Разложить по системам. systemCount — сколько узлов в графе.
    void resize(uint32_t systemCount) { entries_.assign(systemCount, Entry{}); }

    const Entry& at(uint32_t system) const { return entries_[system]; }
    uint32_t size() const { return uint32_t(entries_.size()); }

private:
    std::vector<Entry> entries_;
};

// ---------------------------------------------------------------------------
// Системы тика
// ---------------------------------------------------------------------------

/// Пересобрать карту присутствия. Должна идти ДО осады.
void systemPresence(World& world, const TickContext& context);

/// Осада, занятие ничьих систем и восстановление обороны.
void systemSiege(World& world, const TickContext& context);

/// Зарегистрировать компоненты владения. После галактики и флотов.
void registerControlComponents(World& world);

/// Навесить владение, оборону и состояние осады на все системы галактики.
///
/// Компоненты навешиваются СРАЗУ ВСЕМ, включая ничьи. Смена владельца тогда
/// становится записью в поле, а не добавлением компонента: сущность не
/// переезжает между таблицами, и захват можно обрабатывать прямо в обходе.
void initialiseControl(World& world, const Galaxy& galaxy);

}  // namespace pw::sim
